def draw_elem(c):
    """rax = index: draws one element (clipped to its parents)."""
    a = c
    look, nohover, autohover, pressed, notpressed, enabled, focus, kinds = (
        c.lab(h) for h in ("dl", "dnh", "dah", "dp", "dnp", "den", "dfo", "dk"))
    done = c.lab("dd")
    c.here("bw_draw_elem")
    c.enter(2)                          # 0 i, 1 e
    c.sv(0, RAX)
    c.el(RBX, RAX)
    c.sv(1, RBX)
    c.call("bw_clip_of")
    c.call("bw_sclip")
    c.lv(RBX, 1)
    c.lea(RSI, RBX, STYLE)
    c.address(RDI, "bw_sty")
    c.set(RCX, 128)
    c.copy_bytes()
    # looks: hovered / open, pressed, disabled, focused
    c.address(R12, "bw_sty")
    c.load(R13, RBX, FLAGS)
    c.load(R14, RBX, KIND)
    c.bit(R13, HOVERED | OPEN)
    c.jump_if(EQUAL, nohover)
    c.bit(R13, HOVERSTYLE)
    c.jump_if(EQUAL, autohover)
    c.load(RAX, RBX, HOVER)
    c.store(R12, COL, RAX)
    c.load(RCX, RBX, HOVER2)
    c.jnz(RCX, look + "2")
    c.mov(RCX, RAX)
    c.here(look + "2")
    c.store(R12, COL2, RCX)
    c.load(RAX, RBX, HOVERT)
    c.jz(RAX, nohover)
    c.store(R12, TCOL, RAX)
    c.jump(nohover)
    c.here(autohover)
    c.jc(R14, BUTTON, EQUAL, autohover + "y")
    c.jc(R14, MENU, NOT_EQUAL, nohover)
    c.here(autohover + "y")
    for off in (COL, COL2):
        c.load(RAX, R12, off)
        c.lighten(RAX)
        c.store(R12, off, RAX)
    c.here(nohover)
    c.mov(RAX, R13)
    c.op_n("and", RAX, HOVERED | PRESSED)
    c.jc(RAX, HOVERED | PRESSED, NOT_EQUAL, notpressed)
    for off in (COL, COL2):
        c.load(RAX, R12, off)
        c.darken(RAX)
        c.store(R12, off, RAX)
    c.here(notpressed)
    c.bit(R13, DISABLED)
    c.jump_if(EQUAL, enabled)
    c.load(RAX, R12, TRANSP)
    c.op_n("add", RAX, 255)
    c.shift_right(RAX, 1)
    c.store(R12, TRANSP, RAX)
    c.here(enabled)
    c.jc(R14, INPUT, NOT_EQUAL, focus)
    c.bit(R13, FOCUSED)
    c.jump_if(EQUAL, focus)
    c.put(R12, BORDERC, ACCENT)
    c.load(RAX, R12, BORDER)
    c.jnz(RAX, focus)
    c.put(R12, BORDER, 1)
    c.here(focus)
    c.mov(RAX, R12)
    c.call("bw_scale_style")
    # what to draw for each kind
    c.lv(RBX, 1)
    c.load(R14, RBX, KIND)
    c.jc(R14, TABS, EQUAL, kinds + "tabs")
    c.jc(R14, GL, EQUAL, kinds + "gl")
    c.load(R8, RBX, X)
    c.load(R9, RBX, Y)
    c.load(R10, RBX, W)
    c.load(RCX, RBX, H)
    c.address(RDX, "bw_sty")
    c.address(R11, "bw_blk")
    for k, r in enumerate((R8, R9, R10, RCX, RDX)):
        c.store(R11, 8 * k, r)
    c.call("bw_pbox")
    c.lv(RBX, 1)
    c.load(R14, RBX, KIND)
    c.lv(RAX, 0)
    c.jc(R14, BUTTON, EQUAL, kinds + "label")
    c.jc(R14, MENU, EQUAL, kinds + "label")
    c.jc(R14, INPUT, EQUAL, kinds + "input")
    c.jc(R14, CANVAS, EQUAL, kinds + "canvas")
    c.jc(R14, TEXTK, NOT_EQUAL, done)
    c.mov(RAX, RBX)
    c.set(RCX, 1)
    c.load(RDX, RBX, W)
    c.load(R8, RBX, WU)
    c.jc(R8, 7, NOT_EQUAL, kinds + "w")
    c.set(RDX, -1)
    c.here(kinds + "w")
    c.call("bw_lines")
    c.jump(done)
    for lab, routine in (("label", "bw_label"), ("input", "bw_draw_input"), ("canvas", "bw_draw_shapes"),
                         ("tabs", "bw_draw_tabs"), ("gl", "bw_draw_gl")):
        c.here(kinds + lab)
        c.lv(RAX, 0)
        c.call(routine)
        c.jump(done)
    c.here(done)
    c.leave(2)


