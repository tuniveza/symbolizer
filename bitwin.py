def depth_moves(c):
    """bw_front, bw_back, bw_in_front_of, bw_behind, bw_normalize."""
    for name, front in (("bw_front", True), ("bw_back", False)):
        done = c.lab("fb")
        c.here(name)
        c.enter(1)
        c.sv(0, RAX)
        c.valid(RAX, done)
        c.call("bw_depth_range")
        if front:
            c.lea(R12, RAX, 1)
        else:
            c.lea(R12, RCX, -1)
        c.lv(RAX, 0)
        c.el(RDX, RAX)
        c.store(RDX, DEPTH, R12)
        c.dirty()
        c.here(done)
        c.leave(1)
    for name, step in (("bw_in_front_of", 1), ("bw_behind", -1)):
        done = c.lab("ib")
        c.here(name)
        c.enter(2)
        c.sv(0, RAX)
        c.sv(1, RCX)
        c.valid(RAX, done, 1)
        c.valid(RCX, done, 1)
        c.jr(RAX, RCX, EQUAL, done)
        c.call("bw_normalize")
        c.lv(RCX, 1)
        c.el(RDX, RCX)
        c.load(R8, RDX, DEPTH)
        c.op_n("add", R8, step)
        c.lv(RAX, 0)
        c.el(RDX, RAX)
        c.store(RDX, DEPTH, R8)
        c.dirty()
        c.here(done)
        c.leave(2)
    # bw_normalize: depths become 2, 4, 6 ... in the current order, so "just in front / behind" is exact
    loop, done = c.lab("nm"), c.lab("nmd")
    c.here("bw_normalize")
    c.call("bw_sort")
    c.g(R8, "bw_order_n")
    c.address(R9, "bw_order")
    c.set(R12, 0)
    c.here(loop)
    c.jr(R12, R8, NOT_LESS, done)
    c.mov(R10, R12)
    c.shift_left(R10, 3)
    c.op("add", R10, R9)
    c.load(RAX, R10)
    c.el(RDX, RAX)
    c.lea(RAX, R12, 1)
    c.op("add", RAX, RAX)
    c.store(RDX, DEPTH, RAX)
    c.op_n("add", R12, 1)
    c.jump(loop)
    c.here(done)
    c.ret()


def shapes(c):
    """bw_draw (rax = canvas, rcx = a 64-byte shape, copied) and bw_clear (rax = canvas)."""
    have, room, done = c.lab("dwh"), c.lab("dwr"), c.lab("dwd")
    c.here("bw_draw")
    c.enter(4)                          # 0 index, 1 shape, 2 list, 3 new capacity
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.valid(RAX, done)
    c.el(RDX, RAX)
    c.load(R8, RDX, KIND)
    c.jc(R8, CANVAS, NOT_EQUAL, done)
    c.load(R8, RDX, DATA)
    c.jnz(R8, have)
    c.set(RCX, 16 + 16 * 64)
    c.call("alloc")
    c.put(RAX, 8, 16)
    c.lv(RDX, 0)
    c.el(RDX, RDX)
    c.store(RDX, DATA, RAX)
    c.mov(R8, RAX)
    c.here(have)
    c.load(R9, R8, 0)
    c.load(R10, R8, 8)
    c.jr(R9, R10, LESS, room)
    # full: a list twice as big, the shapes copied over
    c.sv(2, R8)
    c.op("add", R10, R10)
    c.jc(R10, 16, NOT_LESS, have + "c")
    c.set(R10, 16)
    c.here(have + "c")
    c.sv(3, R10)
    c.mov(RCX, R10)
    c.shift_left(RCX, 6)
    c.op_n("add", RCX, 16)
    c.call("alloc")
    c.lv(RSI, 2)
    c.mov(RDI, RAX)
    c.load(RCX, RSI, 0)
    c.shift_left(RCX, 6)
    c.op_n("add", RCX, 16)
    c.copy_bytes()
    c.lv(R10, 3)
    c.store(RAX, 8, R10)
    c.lv(RDX, 0)
    c.el(RDX, RDX)
    c.store(RDX, DATA, RAX)
    c.mov(R8, RAX)
    c.load(R9, R8, 0)
    c.here(room)
    c.mov(RDI, R9)
    c.shift_left(RDI, 6)
    c.op("add", RDI, R8)
    c.op_n("add", RDI, 16)
    c.lv(RSI, 1)
    c.set(RCX, 64)
    c.copy_bytes()
    c.op_n("add", R9, 1)
    c.store(R8, 0, R9)
    c.dirty()
    c.here(done)
    c.leave(4)

    done = c.lab("cld")
    c.here("bw_clear")
    c.valid(RAX, done)
    c.el(RDX, RAX)
    c.load(R8, RDX, KIND)
    c.jc(R8, CANVAS, NOT_EQUAL, done)
    c.load(R8, RDX, DATA)
    c.jz(R8, done)
    c.put(R8, 0, 0)
    c.dirty()
    c.here(done)
    c.ret()


