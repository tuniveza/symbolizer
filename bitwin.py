def draw_shapes(c):
    """rax = index: a canvas's shapes, relative to it and clipped to it."""
    loop, nxt, done = c.lab("shl"), c.lab("shn"), c.lab("shd")
    kinds = {k: c.lab(f"sh{k}") for k in (1, 2, 3, 4, 5, 6)}
    c.here("bw_draw_shapes")
    c.enter(4)                          # 0 i, 1 e, 2 k, 3 shape
    c.sv(0, RAX)
    c.el(RBX, RAX)
    c.sv(1, RBX)
    c.call("bw_clip_of")
    c.lv(RAX, 1)
    c.call("bw_clip_in")
    c.call("bw_sclip")
    c.set(RAX, 0)
    c.sv(2, RAX)
    c.here(loop)
    c.lv(RBX, 1)
    c.load(R8, RBX, DATA)
    c.jz(R8, done)
    c.lv(R9, 2)
    c.load(R10, R8, 0)
    c.jr(R9, R10, NOT_LESS, done)
    c.shift_left(R9, 6)
    c.lea(RSI, R8, 16)
    c.op("add", RSI, R9)
    c.sv(3, RSI)
    c.op_n("add", RSI, 8)
    c.address(RDI, "bw_blk")
    c.set(RCX, 56)
    c.copy_bytes()
    c.address(R11, "bw_blk")
    c.lv(RSI, 3)
    c.load(RAX, RSI, 0)
    c.op_n("and", RAX, 255)
    c.load(R8, RBX, X)
    c.load(R9, RBX, Y)
    for k, lab in kinds.items():
        c.jc(RAX, k, EQUAL, lab)
    c.jump(nxt)

    def shift(*offs):
        for off in offs:
            c.load(RAX, R11, off)
            c.op("add", RAX, R9 if off % 16 else R8)
            c.store(R11, off, RAX)

    def solid(colour_reg):
        c.address(RDX, "bw_ssty")
        c.put(RDX, FILL, 1)
        c.store(RDX, COL, colour_reg)

    for k, routine in ((1, "bw_pbox"), (2, "bw_pell")):
        c.here(kinds[k])
        own = c.lab("sho")
        shift(0, 8)
        c.load(RAX, R11, 32)
        c.jnz(RAX, own)
        c.load(RCX, RSI, 48)
        solid(RCX)
        c.store(R11, 32, RDX)
        c.address(RAX, "bw_ssty")
        c.jump(own + "s")
        c.here(own)                     # its own style: a scaled copy
        c.call("bw_style_copy")
        c.address(R11, "bw_blk")
        c.store(R11, 32, RAX)
        c.here(own + "s")
        c.call(routine)
        c.jump(nxt)

    c.here(kinds[3])                    # line
    shift(0, 8, 16, 24)
    for off in (0, 8, 16, 24, 40):
        c.set(RCX, off)
        c.call("bw_sfield")
    c.address(R11, "bw_blk")
    c.load(RAX, R11, 40)
    c.jc(RAX, 0, GREATER, kinds[3] + "t")
    c.put(R11, 40, 1)
    c.here(kinds[3] + "t")
    c.address(RAX, "bw_blk")
    c.call("paint_line")
    c.jump(nxt)

    c.here(kinds[4])                    # triangle (its transparency rides in the kind field)
    shift(0, 8, 16, 24, 32, 40)
    c.load(RAX, RSI, 0)
    c.shift_right(RAX, 8)
    c.store(R11, 56, RAX)
    for off in (0, 8, 16, 24, 32, 40):
        c.set(RCX, off)
        c.call("bw_sfield")
    c.address(RAX, "bw_blk")
    c.call("paint_triangle")
    c.jump(nxt)

    c.here(kinds[5])                    # text
    shift(0, 8)
    c.load(RAX, R11, 32)
    c.jc(RAX, 0, GREATER, kinds[5] + "s")
    c.put(R11, 32, 16)
    c.here(kinds[5] + "s")
    c.call("bw_ptext")
    c.jump(nxt)

    c.here(kinds[6])                    # dot: {6, x, y, diameter (0 = 6), colour}, centred on x, y
    c.load(RCX, RSI, 24)
    c.jc(RCX, 0, GREATER, kinds[6] + "d")
    c.set(RCX, 6)
    c.here(kinds[6] + "d")
    c.mov(RDX, RCX)
    c.shift_right(RDX, 1)
    c.load(RAX, RSI, 8)
    c.op("add", RAX, R8)
    c.op("sub", RAX, RDX)
    c.load(R10, RSI, 16)
    c.op("add", R10, R9)
    c.op("sub", R10, RDX)
    c.store(R11, 0, RAX)
    c.store(R11, 8, R10)
    c.store(R11, 16, RCX)
    c.store(R11, 24, RCX)
    c.load(RCX, RSI, 32)
    solid(RCX)
    c.store(R11, 32, RDX)
    c.call("bw_pell")

    c.here(nxt)
    c.lv(RAX, 2)
    c.op_n("add", RAX, 1)
    c.sv(2, RAX)
    c.jump(loop)
    c.here(done)
    c.leave(4)


