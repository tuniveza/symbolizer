def frame(c):
    """Lays everything out, draws it all and shows it (wl_present)."""
    bar, barnext, nobar, loop, nxt, done = (c.lab(h) for h in ("fb", "fbn", "fnb", "fl", "fn", "fd"))
    c.here("bw_frame")
    c.enter(3)                          # 0 k, 1 bar height, 2 i
    c.g(RAX, "bw_open_now")
    c.jz(RAX, done)
    c.gi("bw_dirty", 0)
    c.call("bw_layout")
    c.call("bw_sort")
    c.call("paint_clip_all")
    c.address(RAX, "bw_elements")
    c.lea(RAX, RAX, STYLE)
    c.call("bw_style_copy")
    c.mov(RDX, RAX)
    c.address(RBX, "bw_elements")
    c.load(R10, RBX, W)
    c.load(RCX, RBX, H)
    c.set(R8, 0)
    c.blk(R8, R8, R10, RCX, RDX)
    c.call("bw_pbox")
    # the menu bar: as tall as the menus along the top of the window
    c.set(R12, 0)
    c.set(R13, 1)
    c.here(bar)
    c.g(R8, "bw_count")
    c.jr(R13, R8, NOT_LESS, barnext)
    c.el(RBX, R13)
    c.load(RAX, RBX, KIND)
    c.jc(RAX, MENU, NOT_EQUAL, bar + "n")
    c.load(RAX, RBX, SHOWN)
    c.jz(RAX, bar + "n")
    c.load(RAX, RBX, PARENT)
    c.jnz(RAX, bar + "n")
    c.load(RAX, RBX, Y)
    c.jnz(RAX, bar + "n")
    c.load(RAX, RBX, H)
    c.maxr(R12, RAX)
    c.here(bar + "n")
    c.op_n("add", R13, 1)
    c.jump(bar)
    c.here(barnext)
    c.sv(1, R12)
    c.jz(R12, nobar)
    c.address(RAX, "bw_bar_style")
    c.call("bw_style_copy")
    c.mov(RDX, RAX)
    c.address(RBX, "bw_elements")
    c.load(R10, RBX, W)
    c.lv(RCX, 1)
    c.set(R8, 0)
    c.blk(R8, R8, R10, RCX, RDX)
    c.call("bw_pbox")
    c.address(RAX, "bw_barline_style")
    c.call("bw_style_copy")
    c.mov(RDX, RAX)
    c.address(RBX, "bw_elements")
    c.load(R10, RBX, W)
    c.lv(R9, 1)
    c.set(R8, 0)
    c.blk(R8, R9, R10, (0, 1), RDX)
    c.call("bw_pbox")
    c.here(nobar)
    # the elements, back to front
    c.set(RAX, 0)
    c.sv(0, RAX)
    c.here(loop)
    c.lv(RAX, 0)
    c.g(RCX, "bw_order_n")
    c.jr(RAX, RCX, NOT_LESS, nxt)
    c.shift_left(RAX, 3)
    c.address(RCX, "bw_order")
    c.op("add", RAX, RCX)
    c.load(RAX, RAX)
    c.el(RBX, RAX)
    c.load(RCX, RBX, SHOWN)
    c.jz(RCX, loop + "n")
    c.call("bw_draw_elem")
    c.here(loop + "n")
    c.lv(RAX, 0)
    c.op_n("add", RAX, 1)
    c.sv(0, RAX)
    c.jump(loop)
    c.here(nxt)
    c.call("bw_draw_menu_list")
    c.call("wl_present")
    c.here(done)
    c.leave(3)


