def hit(c):
    """rax = x, rcx = y (logical) -> rax = the frontmost shown, enabled element there (0 = the window,
    -2 = the open menu's item list), rcx = the item or tab under the pointer (-1 = none)."""
    elems, loop, nxt, found, none = c.lab("he"), c.lab("hl"), c.lab("hn"), c.lab("hf"), c.lab("hx")
    c.here("bw_hit")
    c.enter(4)                          # 0 x, 1 y, 2 k, 3 i
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.g(RAX, "bw_menu")
    c.jc(RAX, 0, LESS, elems)
    c.call("bw_menu_geom")
    c.address(RSI, "bw_ml")
    c.load(R12, RSI, 40)
    c.jz(R12, elems)
    c.lv(RAX, 0)
    c.lv(RCX, 1)
    c.load(R8, RSI, 0)
    c.jr(RAX, R8, LESS, elems)
    c.load(R9, RSI, 16)
    c.op("add", R8, R9)
    c.jr(RAX, R8, NOT_LESS, elems)
    c.load(R8, RSI, 8)
    c.jr(RCX, R8, LESS, elems)
    c.load(R9, RSI, 24)
    c.op("add", R9, R8)
    c.jr(RCX, R9, NOT_LESS, elems)
    c.mov(RAX, RCX)
    c.op("sub", RAX, R8)
    c.op_n("sub", RAX, 4)
    c.load(RCX, RSI, 32)
    c.sign_extend()
    c.divide(RCX, signed=True)
    c.set(R8, 0)
    c.maxr(RAX, R8)
    c.op_n("sub", R12, 1)
    c.minr(RAX, R12)
    c.mov(RCX, RAX)
    c.set(RAX, -2)
    c.leave(4)
    c.here(elems)
    c.g(RAX, "bw_order_n")
    c.op_n("sub", RAX, 1)
    c.sv(2, RAX)
    c.here(loop)
    c.lv(RAX, 2)
    c.jc(RAX, 0, LESS, none)
    c.shift_left(RAX, 3)
    c.address(RCX, "bw_order")
    c.op("add", RAX, RCX)
    c.load(RAX, RAX)
    c.sv(3, RAX)
    c.el(RBX, RAX)
    c.load(RAX, RBX, SHOWN)
    c.jz(RAX, nxt)
    c.load(R8, RBX, FLAGS)
    c.bit(R8, DISABLED)
    c.jump_if(NOT_EQUAL, nxt)
    c.load(RAX, RBX, KIND)
    c.jc(RAX, WINDOW, EQUAL, nxt)
    c.jc(RAX, TEXTK, NOT_EQUAL, nxt + "t")
    c.load(RAX, RBX, CLICK)             # a text only catches the pointer when it does something
    c.jnz(RAX, nxt + "t")
    c.bit(R8, HOVERSTYLE)
    c.jump_if(EQUAL, nxt)
    c.here(nxt + "t")
    c.lv(RAX, 0)
    c.lv(RCX, 1)
    c.load(R8, RBX, X)
    c.jr(RAX, R8, LESS, nxt)
    c.load(R9, RBX, W)
    c.op("add", R8, R9)
    c.jr(RAX, R8, NOT_LESS, nxt)
    c.load(R8, RBX, Y)
    c.jr(RCX, R8, LESS, nxt)
    c.load(R9, RBX, H)
    c.op("add", R8, R9)
    c.jr(RCX, R8, NOT_LESS, nxt)
    c.lv(RAX, 3)
    c.call("bw_clip_of")
    c.lv(R8, 0)
    c.lv(R9, 1)
    c.load(RCX, RAX, 0)
    c.jr(R8, RCX, LESS, nxt)
    c.load(RCX, RAX, 16)
    c.jr(R8, RCX, NOT_LESS, nxt)
    c.load(RCX, RAX, 8)
    c.jr(R9, RCX, LESS, nxt)
    c.load(RCX, RAX, 24)
    c.jr(R9, RCX, NOT_LESS, nxt)
    c.jump(found)
    c.here(nxt)
    c.lv(RAX, 2)
    c.op_n("sub", RAX, 1)
    c.sv(2, RAX)
    c.jump(loop)
    c.here(found)
    c.lv(RAX, 3)
    c.el(RBX, RAX)
    c.load(R8, RBX, KIND)
    c.set(RCX, -1)
    c.jc(R8, TABS, NOT_EQUAL, found + "r")
    c.lv(RCX, 0)
    c.call("bw_tab_at")
    c.mov(RCX, RAX)
    c.lv(RAX, 3)
    c.here(found + "r")
    c.leave(4)
    c.here(none)
    c.set(RAX, 0)
    c.set(RCX, -1)
    c.leave(4)


def events(c):
    """bw_event: rax = kind, rcx, rdx, r8 from wl_event. Plus bw_set_hover, bw_set_focus, bw_close_menu,
    bw_choose and bw_click."""
    # bw_set_hover: rax = element to show as hovered (-1 = none)
    done = c.lab("shd")
    c.here("bw_set_hover")
    c.g(R12, "bw_hover")
    c.jr(RAX, R12, EQUAL, done)
    c.mov(R13, RAX)
    c.valid(R12, done + "o")
    c.el(RDX, R12)
    c.flag_off(RDX, HOVERED)
    c.put(RDX, HOVITEM, 0)
    c.here(done + "o")
    c.valid(R13, done + "n")
    c.el(RDX, R13)
    c.flag_on(RDX, HOVERED)
    c.here(done + "n")
    c.sg("bw_hover", R13)
    c.dirty()
    c.here(done)
    c.ret()

    # bw_set_focus: rax = input box to focus (-1 = none)
    done = c.lab("sfd")
    c.here("bw_set_focus")
    c.g(R12, "bw_focus")
    c.jr(RAX, R12, EQUAL, done)
    c.mov(R13, RAX)
    c.valid(R12, done + "o")
    c.el(RDX, R12)
    c.flag_off(RDX, FOCUSED)
    c.here(done + "o")
    c.valid(R13, done + "n")
    c.el(RDX, R13)
    c.flag_on(RDX, FOCUSED)
    c.load(RAX, RDX, TEXT)
    c.set(RCX, 0)
    c.jz(RAX, done + "e")
    c.load(RCX, RAX)
    c.here(done + "e")
    c.store(RDX, DATA, RCX)             # the caret goes to the end
    c.here(done + "n")
    c.sg("bw_focus", R13)
    c.dirty()
    c.here(done)
    c.ret()

    # bw_close_menu
    done = c.lab("cmd")
    c.here("bw_close_menu")
    c.g(RAX, "bw_menu")
    c.jc(RAX, 0, LESS, done)
    c.valid(RAX, done + "x")
    c.el(RDX, RAX)
    c.flag_off(RDX, OPEN)
    c.here(done + "x")
    c.gi("bw_menu", -1)
    c.gi("bw_menu_item", -1)
    c.dirty()
    c.here(done)
    c.ret()

    def count_click(idx_reg):
        c.sg("bw_last", idx_reg)
        c.sg("bw_clicked", idx_reg)
        c.g(R10, "bw_click_count")
        c.op_n("add", R10, 1)
        c.sg("bw_click_count", R10)

    # bw_choose: rax = item of the open menu
    done = c.lab("chd")
    c.here("bw_choose")
    c.enter(3)                          # 0 item, 1 menu, 2 handler
    c.sv(0, RAX)
    c.g(RAX, "bw_menu")
    c.sv(1, RAX)
    c.set(RAX, 0)
    c.sv(2, RAX)
    c.call("bw_close_menu")
    c.lv(RAX, 1)
    c.valid(RAX, done)
    c.el(RDX, RAX)
    c.lv(RCX, 0)
    c.store(RDX, PICKED, RCX)
    c.load(R8, RDX, ITEMS)
    c.jz(R8, done + "c")
    c.jc(RCX, 0, LESS, done + "c")
    c.load(R9, R8, 0)
    c.jr(RCX, R9, NOT_LESS, done + "c")
    c.shift_left(RCX, 4)
    c.op("add", RCX, R8)
    c.load(RAX, RCX, 8)
    c.sg("bw_chosen", RAX)
    c.load(RAX, RCX, 16)
    c.sv(2, RAX)
    c.here(done + "c")
    c.lv(RAX, 1)
    count_click(RAX)
    c.lv(RAX, 2)
    c.handler(RAX)
    c.here(done)
    c.leave(3)

    # bw_click: rax = element, rcx = item under the pointer (tabs)
    plain, tabs, done = c.lab("ckp"), c.lab("ckt"), c.lab("ckd")
    c.here("bw_click")
    c.enter(3)                          # 0 element, 1 item, 2 handler
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.sg("bw_last", RAX)
    c.el(RDX, RAX)
    c.load(R8, RDX, KIND)
    c.jc(R8, TABS, NOT_EQUAL, plain)
    c.jc(RCX, 0, LESS, plain)
    c.load(R8, RDX, PICKED)
    c.jr(RCX, R8, EQUAL, plain)
    c.load(R8, RDX, ITEMS)
    c.jz(R8, plain)
    c.load(R9, R8, 0)
    c.jr(RCX, R9, NOT_LESS, plain)
    c.store(RDX, PICKED, RCX)           # a new tab picked: its page shows
    c.shift_left(RCX, 4)
    c.op("add", RCX, R8)
    c.load(RAX, RCX, 8)
    c.sg("bw_chosen", RAX)
    c.load(RAX, RCX, 16)
    c.sv(2, RAX)
    c.dirty()
    c.lv(RAX, 0)
    count_click(RAX)
    c.lv(RAX, 2)
    c.handler(RAX)
    c.lv(RAX, 0)
    c.el(RDX, RAX)
    c.load(RAX, RDX, CHANGE)
    c.handler(RAX)
    c.leave(3)
    c.here(plain)
    c.lv(RAX, 0)
    count_click(RAX)
    c.lv(RAX, 0)
    c.el(RDX, RAX)
    c.load(RAX, RDX, CLICK)
    c.handler(RAX)
    c.leave(3)

    # bw_event
    kinds = {k: c.lab(f"ev{k}") for k in (1, 2, 3, 4, 5, 6, 7, 8)}
    out = c.lab("evo")
    c.here("bw_event")
    c.enter(7)                          # 0 kind, 1 a, 2 b, 3 c, 4 hit, 5 item, 6 spare
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.sv(2, RDX)
    c.sv(3, R8)
    for k, lab in kinds.items():
        c.jc(RAX, k, EQUAL, lab)
    c.here(out)
    c.leave(7)

    def pointer():
        """mouse x, y in logical px; hit test; hover; the open menu's hovered item."""
        nomenu = c.lab("pm")
        for slot, label in ((1, "bw_mouse_x"), (2, "bw_mouse_y")):
            c.lv(RAX, slot)
            c.call("bw_unsc")
            c.sv(slot, RAX)
            c.sg(label, RAX)
        c.lv(RAX, 1)
        c.lv(RCX, 2)
        c.call("bw_hit")
        c.sv(4, RAX)
        c.sv(5, RCX)
        c.g(R8, "bw_menu")
        c.jc(R8, 0, LESS, nomenu)
        c.set(R9, -1)
        c.jc(RAX, -2, NOT_EQUAL, nomenu + "s")
        c.mov(R9, RCX)
        c.here(nomenu + "s")
        c.g(RCX, "bw_menu_item")
        c.jr(RCX, R9, EQUAL, nomenu)
        c.sg("bw_menu_item", R9)
        c.dirty()
        c.here(nomenu)
        c.lv(RAX, 4)
        c.jc(RAX, 1, NOT_LESS, nomenu + "h")
        c.set(RAX, -1)
        c.here(nomenu + "h")
        c.call("bw_set_hover")
        notab = c.lab("pnt")
        c.lv(RAX, 4)
        c.jc(RAX, 1, LESS, notab)
        c.el(RDX, RAX)
        c.load(R8, RDX, KIND)
        c.jc(R8, TABS, NOT_EQUAL, notab)
        c.lv(R9, 5)
        c.op_n("add", R9, 1)
        c.load(R10, RDX, HOVITEM)
        c.jr(R9, R10, EQUAL, notab)
        c.store(RDX, HOVITEM, R9)
        c.dirty()
        c.here(notab)
        c.lv(RAX, 4)
        c.jc(RAX, 0, LESS, notab + "l")
        c.sg("bw_last", RAX)
        c.here(notab + "l")

    # moved / scrolled
    c.here(kinds[1])
    c.here(kinds[7])
    pointer()
    c.g(RAX, "bw_on_move")
    c.handler(RAX)
    c.leave(7)

    # pressed
    nomenu, notmenu, openmenu = c.lab("pn"), c.lab("pnm"), c.lab("pom")
    c.here(kinds[2])
    pointer()
    c.lv(R8, 3)
    c.jc(R8, 1, NOT_EQUAL, out)         # only the left button clicks
    c.g(R8, "bw_menu")
    c.jc(R8, 0, LESS, nomenu)
    c.lv(RAX, 4)
    c.jc(RAX, -2, NOT_EQUAL, nomenu + "l")
    c.gi("bw_press", -2)                # pressed in the open list: chosen on release
    c.leave(7)
    c.here(nomenu + "l")
    c.sv(6, R8)
    c.call("bw_close_menu")             # a press anywhere else closes the open menu
    c.lv(RAX, 4)
    c.lv(R8, 6)
    c.jr(RAX, R8, EQUAL, out)           # (its own button: just closed)
    c.jc(RAX, 1, LESS, out)
    c.el(RDX, RAX)
    c.load(R8, RDX, KIND)
    c.jc(R8, MENU, EQUAL, openmenu)     # another menu: open that one instead
    c.leave(7)
    c.here(nomenu)
    c.lv(RAX, 4)
    c.jc(RAX, 1, LESS, notmenu)
    c.el(RDX, RAX)
    c.load(R8, RDX, KIND)
    c.jc(R8, MENU, EQUAL, openmenu)
    c.here(notmenu)
    c.set(RAX, -1)                      # focus: the input box pressed, or none
    c.lv(RCX, 4)
    c.jc(RCX, 1, LESS, notmenu + "f")
    c.el(RDX, RCX)
    c.load(R8, RDX, KIND)
    c.jc(R8, INPUT, NOT_EQUAL, notmenu + "f")
    c.mov(RAX, RCX)
    c.here(notmenu + "f")
    c.call("bw_set_focus")
    c.lv(RAX, 4)
    c.sg("bw_press", RAX)
    c.jc(RAX, 1, LESS, out)
    c.el(RDX, RAX)
    c.flag_on(RDX, PRESSED)
    c.dirty()
    c.leave(7)
    c.here(openmenu)
    c.lv(RAX, 4)
    c.el(RDX, RAX)
    c.flag_on(RDX, OPEN)
    c.sg("bw_menu", RAX)
    c.sg("bw_last", RAX)
    c.gi("bw_menu_item", -1)
    c.gi("bw_press", -1)
    c.dirty()
    c.leave(7)

    # released
    c.here(kinds[3])
    pointer()
    c.lv(R8, 3)
    c.jc(R8, 1, NOT_EQUAL, out)
    c.g(RAX, "bw_press")
    c.sv(6, RAX)
    c.gi("bw_press", -1)
    c.jc(RAX, 1, LESS, kinds[3] + "n")
    c.el(RDX, RAX)
    c.flag_off(RDX, PRESSED)
    c.dirty()
    c.here(kinds[3] + "n")
    c.lv(RAX, 4)
    c.jc(RAX, -2, NOT_EQUAL, kinds[3] + "i")
    c.g(R8, "bw_menu")
    c.jc(R8, 0, LESS, kinds[3] + "i")
    c.lv(RAX, 5)
    c.call("bw_choose")
    c.leave(7)
    c.here(kinds[3] + "i")
    c.lv(RAX, 6)
    c.jc(RAX, 0, LESS, out)
    c.lv(RCX, 4)
    c.jr(RAX, RCX, NOT_EQUAL, out)
    c.lv(RCX, 5)
    c.call("bw_click")
    c.leave(7)

    # key
    nofocus = c.lab("kn")
    c.here(kinds[4])
    c.lv(RAX, 1)
    c.sg("bw_key", RAX)
    c.jc(RAX, 27, NOT_EQUAL, nofocus + "e")
    c.call("bw_close_menu")
    c.here(nofocus + "e")
    c.g(RAX, "bw_focus")
    c.jc(RAX, 1, LESS, nofocus)
    c.sg("bw_last", RAX)
    c.lv(RCX, 1)
    c.lv(RDX, 2)
    c.call("bw_edit")
    c.jz(RAX, nofocus)
    c.g(RAX, "bw_focus")                # enter: the input box's on change
    c.el(RDX, RAX)
    c.load(RAX, RDX, CHANGE)
    c.handler(RAX)
    c.here(nofocus)
    c.g(RAX, "bw_on_key")
    c.handler(RAX)
    c.leave(7)

    # resized
    c.here(kinds[5])
    c.dirty()
    c.g(RAX, "bw_on_resize")
    c.handler(RAX)
    c.leave(7)

    # closed by the person
    c.here(kinds[6])
    c.g(RAX, "bw_on_close")
    c.handler(RAX)
    c.call("bw_close")
    c.leave(7)

    # the pointer left
    c.here(kinds[8])
    c.set(RAX, -1)
    c.call("bw_set_hover")
    c.gi("bw_menu_item", -1)
    c.dirty()
    c.leave(7)


def edit(c):
    """rax = input box, rcx = key, rdx = 1 if ctrl -> its text and caret edited; rax = 1 if it was enter."""
    keys = {k: c.lab(f"ek{k}") for k in (10, 8, 1001, 1002, 1005, 1006, 1007)}
    store, zero = c.lab("eks"), c.lab("ekz")
    c.here("bw_edit")
    c.enter(7)                          # 0 i, 1 key, 2 ctrl, 3 e, 4 text, 5 length, 6 caret
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.sv(2, RDX)
    c.el(RBX, RAX)
    c.sv(3, RBX)
    c.textof(RAX, RBX)
    c.sv(4, RAX)
    c.load(RCX, RAX)
    c.sv(5, RCX)
    c.load(RDX, RBX, DATA)
    c.minr(RDX, RCX)
    c.set(R8, 0)
    c.maxr(RDX, R8)
    c.sv(6, RDX)
    c.dirty()
    c.lv(RAX, 1)
    for k, lab in keys.items():
        c.jc(RAX, k, EQUAL, lab)
    # a character
    c.lv(R8, 2)
    c.jnz(R8, zero)
    c.jc(RAX, 32, LESS, zero)
    c.jc(RAX, 127, EQUAL, zero)
    c.jc(RAX, 255, GREATER, zero)
    c.lv(RCX, 5)
    c.jc(RCX, 4000, NOT_LESS, zero)
    c.mov(R8, RAX)
    c.lv(RAX, 4)
    c.lv(RCX, 6)
    c.set(RDX, 0)
    c.call("bw_splice")
    c.lv(RBX, 3)
    c.store(RBX, TEXT, RAX)
    c.lv(RDX, 6)
    c.op_n("add", RDX, 1)
    c.jump(store)

    c.here(keys[10])
    c.set(RAX, 1)
    c.leave(7)

    c.here(keys[8])                     # backspace
    c.lv(RCX, 6)
    c.jz(RCX, zero)
    c.op_n("sub", RCX, 1)
    c.sv(6, RCX)
    c.lv(RAX, 4)
    c.set(RDX, 1)
    c.set(R8, -1)
    c.call("bw_splice")
    c.lv(RBX, 3)
    c.store(RBX, TEXT, RAX)
    c.lv(RDX, 6)
    c.jump(store)

    c.here(keys[1007])                  # delete
    c.lv(RCX, 6)
    c.lv(RDX, 5)
    c.jr(RCX, RDX, NOT_LESS, zero)
    c.lv(RAX, 4)
    c.set(RDX, 1)
    c.set(R8, -1)
    c.call("bw_splice")
    c.lv(RBX, 3)
    c.store(RBX, TEXT, RAX)
    c.lv(RDX, 6)
    c.jump(store)

    c.here(keys[1001])                  # left
    c.lv(RDX, 6)
    c.op_n("sub", RDX, 1)
    c.set(R8, 0)
    c.maxr(RDX, R8)
    c.jump(store)
    c.here(keys[1002])                  # right
    c.lv(RDX, 6)
    c.op_n("add", RDX, 1)
    c.lv(R8, 5)
    c.minr(RDX, R8)
    c.jump(store)
    c.here(keys[1005])                  # home
    c.set(RDX, 0)
    c.jump(store)
    c.here(keys[1006])                  # end
    c.lv(RDX, 5)

    c.here(store)
    c.lv(RBX, 3)
    c.store(RBX, DATA, RDX)
    c.here(zero)
    c.set(RAX, 0)
    c.leave(7)


def splice(c):
    """rax = text, rcx = where, rdx = how many bytes to take out, r8 = a byte to put in (-1 = none)
    -> rax = a new text."""
    nochar = c.lab("spn")
    c.here("bw_splice")
    c.enter(5)                          # 0 text, 1 at, 2 remove, 3 char, 4 new text
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.sv(2, RDX)
    c.sv(3, R8)
    c.load(RCX, RAX)
    c.op("sub", RCX, RDX)
    c.jc(R8, 0, LESS, nochar + "l")
    c.op_n("add", RCX, 1)
    c.here(nochar + "l")
    c.call("new_text")
    c.sv(4, RAX)
    c.lea(RDI, RAX, 8)
    c.lv(RSI, 0)
    c.op_n("add", RSI, 8)
    c.lv(RCX, 1)
    c.copy_bytes()
    c.lv(R8, 3)
    c.jc(R8, 0, LESS, nochar)
    c.store_byte(RDI, 0, R8)
    c.op_n("add", RDI, 1)
    c.here(nochar)
    c.lv(RAX, 0)
    c.load(RCX, RAX)
    c.lv(RDX, 1)
    c.op("sub", RCX, RDX)
    c.lv(R8, 2)
    c.op("sub", RCX, R8)
    c.lea(RSI, RAX, 8)
    c.op("add", RSI, RDX)
    c.op("add", RSI, R8)
    c.copy_bytes()
    c.lv(RAX, 4)
    c.leave(5)


def loop(c):
    """bw_loop: rax = when to stop (stopwatch ns, -1 = never), rcx = click to wait for (-3 = none, -1 = any).
    Draws when needed, fires the timer, waits for events (with a timeout) and handles them."""
    a = c
    top, noclick, nodraw, nodl, notimer, have, notdue, t2, t3, out = (
        c.lab(h) for h in ("lt", "lnc", "lnd", "lndl", "lnt", "lh", "lnu", "lt2", "lt3", "lo"))
    c.here("bw_loop")
    c.enter(5)                          # 0 deadline, 1 target, 2 clicks seen, 3 now, 4 timeout
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.g(RAX, "bw_click_count")
    c.sv(2, RAX)
    c.here(top)
    c.g(RAX, "bw_open_now")
    c.jz(RAX, out)
    c.lv(RAX, 1)
    c.jc(RAX, -3, EQUAL, noclick)
    c.g(RCX, "bw_click_count")
    c.lv(RDX, 2)
    c.jr(RCX, RDX, EQUAL, noclick)
    c.sv(2, RCX)
    c.jc(RAX, -1, EQUAL, out)
    c.g(RCX, "bw_clicked")
    c.jr(RAX, RCX, EQUAL, out)
    c.here(noclick)
    c.g(RAX, "bw_dirty")
    if c.has_gl:
        c.g(RCX, "gl_animating")
        c.op("or", RAX, RCX)
    c.jz(RAX, nodraw)
    c.call("bw_frame")
    c.here(nodraw)
    c.set(RDI, 1)
    c.call("now")
    c.sv(3, RAX)
    c.lv(RCX, 0)
    c.jc(RCX, -1, EQUAL, nodl)
    c.jr(RAX, RCX, NOT_LESS, out)
    c.here(nodl)
    # the timer
    c.g(RAX, "bw_every")
    c.jz(RAX, notimer)
    c.g(RCX, "bw_every_ms")
    c.jc(RCX, 0, NOT_GREATER, notimer)
    c.multiply_n(RCX, RCX, 1000000)
    c.g(RDX, "bw_next_tick")
    c.jnz(RDX, have)
    c.lv(RAX, 3)
    c.op("add", RAX, RCX)
    c.sg("bw_next_tick", RAX)
    c.jump(notimer)
    c.here(have)
    c.lv(RAX, 3)
    c.jr(RAX, RDX, LESS, notimer)
    c.op("add", RDX, RCX)               # due: the next tick, never in the past (no bursts after a stall)
    c.jr(RDX, RAX, GREATER, have + "k")
    c.lea(RDX, RAX, 0)
    c.op("add", RDX, RCX)
    c.here(have + "k")
    c.sg("bw_next_tick", RDX)
    c.dirty()
    c.g(RAX, "bw_every")
    c.handler(RAX)
    c.jump(top)
    c.here(notimer)
    # how long to wait
    c.set(RAX, -1)
    c.sv(4, RAX)

    def candidate():
        """rax = ns from now -> the timeout is at most that many ms (rounded up)."""
        take, keep = c.lab("tk"), c.lab("tp")
        c.op_n("add", RAX, 999999)
        c.set(RCX, 1000000)
        c.sign_extend()
        c.divide(RCX, signed=True)
        c.set(R8, 0)
        c.maxr(RAX, R8)
        c.lv(RCX, 4)
        c.jc(RCX, -1, EQUAL, take)
        c.jr(RAX, RCX, NOT_LESS, keep)
        c.here(take)
        c.sv(4, RAX)
        c.here(keep)

    c.lv(RAX, 0)
    c.jc(RAX, -1, EQUAL, t2)
    c.lv(RCX, 3)
    c.op("sub", RAX, RCX)
    candidate()
    c.here(t2)
    c.g(RAX, "bw_every")
    c.jz(RAX, t3)
    c.g(RAX, "bw_every_ms")
    c.jc(RAX, 0, NOT_GREATER, t3)
    c.g(RAX, "bw_next_tick")
    c.lv(RCX, 3)
    c.op("sub", RAX, RCX)
    candidate()
    c.here(t3)
    if c.has_gl:
        c.g(RAX, "gl_animating")
        c.jz(RAX, t3 + "g")
        c.set(RAX, 16000000)
        candidate()
        c.here(t3 + "g")
    c.lv(RAX, 4)
    c.call("wl_event")
    c.jz(RAX, top)
    c.call("bw_event")
    c.jump(top)
    c.here(out)
    c.leave(5)
