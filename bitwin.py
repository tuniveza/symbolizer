def flow_of(c):
    """rax = index -> rax = the element it flows under (0 = none): the one made before it, skipping ones in
    another parent or on another tab page."""
    loop, step, none, done = c.lab("fw"), c.lab("fws"), c.lab("fwn"), c.lab("fwd")
    c.here("bw_flow_of")
    c.mov(R14, RAX)
    c.el(R8, RAX)
    c.load(R9, R8, FLOW)
    c.load(R12, R8, PARENT)
    c.load(R13, R8, PAGE)
    c.here(loop)
    c.jc(R9, 0, NOT_GREATER, none)
    c.jr(R9, R14, NOT_LESS, none)
    c.el(R10, R9)
    c.load(R15, R10, PARENT)
    c.jr(R15, R12, NOT_EQUAL, step)
    c.load(R15, R10, PAGE)
    c.jz(R15, done)
    c.jr(R15, R13, EQUAL, done)
    c.here(step)
    c.mov(R14, R9)
    c.load(R9, R10, FLOW)
    c.jump(loop)
    c.here(none)
    c.set(R9, 0)
    c.here(done)
    c.mov(RAX, R9)
    c.ret()


def place(c):
    """rax = index (not 0) -> works out its x, y, w, h and shown; rax = 1 if any of them changed."""
    a = c
    c.here("bw_place")
    c.enter(11)     # 0 i, 1 e, 2 parent record, 3 other record, 4 w, 5 h, 6 x, 7 y, 8 shown, 9 flow record or 0
    c.sv(0, RAX)
    c.el(RBX, RAX)
    c.sv(1, RBX)

    def index_field(off, slot):
        zero, ok = c.lab("pz"), c.lab("pk")
        c.lv(RBX, 1)
        c.load(RCX, RBX, off)
        c.valid(RCX, zero)
        c.lv(R9, 0)
        c.jr(RCX, R9, NOT_EQUAL, ok)
        c.here(zero)
        c.set(RCX, 0)
        c.here(ok)
        c.el(RDX, RCX)
        c.sv(slot, RDX)

    index_field(PARENT, 2)
    index_field(OTHER, 3)
    c.lv(RAX, 0)
    c.call("bw_flow_of")
    nf = c.lab("pnf")
    c.set(RDX, 0)
    c.jz(RAX, nf)
    c.el(RDX, RAX)
    c.here(nf)
    c.sv(9, RDX)

    # shown?
    o1, o2, o3, hide = c.lab("ps1"), c.lab("ps2"), c.lab("ps3"), c.lab("psh")
    c.lv(RBX, 1)
    c.set(R12, 1)
    c.load(R8, RBX, FLAGS)
    c.bit(R8, HIDDEN)
    c.jump_if(EQUAL, o1)
    c.set(R12, 0)
    c.here(o1)
    c.lv(RDX, 2)
    c.load(R8, RDX, SHOWN)
    c.jnz(R8, o2)
    c.set(R12, 0)
    c.here(o2)
    c.load(R8, RBX, PAGE)
    c.jz(R8, o3)
    c.mov(R9, R8)
    c.shift_right(R9, 16)
    c.op_n("and", R8, 0xFFFF)
    c.op_n("sub", R8, 1)
    c.valid(R9, o3)
    c.el(R10, R9)
    c.load(R13, R10, PICKED)
    c.jr(R13, R8, NOT_EQUAL, hide)
    c.load(R13, R10, SHOWN)
    c.jnz(R13, o3)
    c.here(hide)
    c.set(R12, 0)
    c.here(o3)
    c.sv(8, R12)

    def size_axis(vo, uo, ps, slot, is_h):
        pct, permille, far, aligned, fitl, done = (c.lab(h) for h in ("zp", "zm", "zf", "za", "zt", "zd"))
        c.lv(RBX, 1)
        c.load(RAX, RBX, vo)
        c.load(RCX, RBX, uo)
        c.jc(RCX, 1, EQUAL, pct)
        c.jc(RCX, 2, EQUAL, far)
        c.jc(RCX, 6, EQUAL, aligned)
        c.jc(RCX, 7, EQUAL, fitl)
        c.jc(RCX, 8, EQUAL, permille)
        c.jump(done)
        for lab, n in ((pct, 100), (permille, 1000)):
            c.here(lab)
            c.lv(RDX, 2)
            c.load(RCX, RDX, ps)
            c.muldiv(n)
            c.jump(done)
        c.here(far)
        c.lv(RDX, 2)
        c.load(RCX, RDX, ps)
        c.op("sub", RCX, RAX)
        c.mov(RAX, RCX)
        c.jump(done)
        c.here(aligned)
        c.lv(RDX, 3)
        c.load(RCX, RDX, ps)
        c.op("add", RAX, RCX)
        c.jump(done)
        c.here(fitl)
        if not is_h:
            c.lv(RAX, 0)
            c.set(RCX, -1)
            c.call("bw_fit")
        else:
            usew = c.lab("zw")
            c.lv(RBX, 1)
            c.load(RCX, RBX, WU)
            c.lv(RDX, 4)
            c.jc(RCX, 7, NOT_EQUAL, usew)
            c.set(RDX, -1)
            c.here(usew)
            c.mov(RCX, RDX)
            c.lv(RAX, 0)
            c.call("bw_fit")
            c.mov(RAX, RCX)
        c.here(done)
        c.jc(RAX, 0, NOT_LESS, done + "p")
        c.set(RAX, 0)
        c.here(done + "p")
        c.sv(slot, RAX)

    size_axis(WV, WU, W, 4, False)
    size_axis(HV, HU, H, 5, True)

    def pos_axis(vo, uo, po, ps, own, slot, is_y):
        labs = {u: c.lab(f"q{u}") for u in (1, 2, 3, 4, 5, 6, 8, 9)}
        done = c.lab("qd")
        c.lv(RBX, 1)
        c.load(RAX, RBX, vo)
        c.load(RCX, RBX, uo)
        c.lv(RDX, 2)
        c.load(R8, RDX, po)             # the parent's start
        c.load(R9, RDX, ps)             # the parent's size
        c.lv(R10, own)                  # this element's size
        c.lv(RDX, 3)                    # the other element
        for u, lab in labs.items():
            c.jc(RCX, u, EQUAL, lab)
        c.op("add", RAX, R8)            # px
        c.jump(done)
        for u, n in ((1, 100), (8, 1000)):
            c.here(labs[u])
            c.mov(R12, R8)
            c.mov(RCX, R9)
            c.muldiv(n)
            c.op("add", RAX, R12)
            c.jump(done)
        c.here(labs[2])                 # from the far edge
        c.mov(R12, R8)
        c.op("add", R12, R9)
        c.op("sub", R12, RAX)
        c.op("sub", R12, R10)
        c.mov(RAX, R12)
        c.jump(done)
        c.here(labs[3])                 # centred
        c.mov(R12, R9)
        c.op("sub", R12, R10)
        c.shift_right_signed(R12, 1)
        c.op("add", R12, R8)
        c.op("add", RAX, R12)
        c.jump(done)
        c.here(labs[4])                 # after the other
        c.load(R12, RDX, po)
        c.op("add", RAX, R12)
        c.load(R12, RDX, ps)
        c.op("add", RAX, R12)
        c.load(R12, RBX, GAP)
        c.op("add", RAX, R12)
        c.jump(done)
        c.here(labs[5])                 # before the other
        c.load(R12, RDX, po)
        c.load(R13, RBX, GAP)
        c.op("sub", R12, R13)
        c.op("sub", R12, R10)
        c.op("add", RAX, R12)
        c.jump(done)
        c.here(labs[6])                 # aligned with the other
        c.load(R12, RDX, po)
        c.op("add", RAX, R12)
        c.jump(done)
        c.here(labs[9])                 # flow: under the element made before
        top, plain = c.lab("qt"), c.lab("qp")
        c.lv(RDX, 9)
        c.jz(RDX, top)
        c.load(R12, RDX, KIND)
        c.jc(R12, MENU, EQUAL, top + "b")
        c.jc(R12, TABS, EQUAL, top + "b")
        if is_y:
            c.load(R12, RDX, Y)
            c.op("add", RAX, R12)
            c.load(R12, RDX, H)
            c.op("add", RAX, R12)
            c.op_n("add", RAX, 10)
        else:
            c.load(R12, RDX, X)
            c.op("add", RAX, R12)
        c.jump(done)
        c.here(top + "b")               # under a menu bar or tabs
        if is_y:
            c.load(R12, RDX, Y)
            c.op("add", RAX, R12)
            c.load(R12, RDX, H)
            c.op("add", RAX, R12)
            c.op_n("add", RAX, 16)
            c.jump(done)
        c.here(top)                     # nothing before: 20 from the parent's corner
        c.op("add", RAX, R8)
        c.op_n("add", RAX, 20)
        c.here(done)
        c.sv(slot, RAX)

    pos_axis(XV, XU, X, W, 4, 6, False)
    pos_axis(YV, YU, Y, H, 5, 7, True)

    c.set(R12, 0)
    c.lv(RBX, 1)
    for slot, off in ((4, W), (5, H), (6, X), (7, Y), (8, SHOWN)):
        same = c.lab("same")
        c.lv(RAX, slot)
        c.load(RCX, RBX, off)
        c.jr(RAX, RCX, EQUAL, same)
        c.set(R12, 1)
        c.store(RBX, off, RAX)
        c.here(same)
    c.mov(RAX, R12)
    c.leave(11)


def layout(c):
    """Everything's x, y, w, h and shown, in logical px. A few passes, so elements placed relative to later ones
    settle too."""
    ok, loop, inner, done = c.lab("lw"), c.lab("lp"), c.lab("li"), c.lab("lpd")
    c.here("bw_layout")
    c.enter(3)                          # 0 i, 1 changed, 2 pass
    c.call("bw_init")
    c.address(RBX, "bw_elements")
    for field, value, off in ((8, WV, W), (16, HV, H)):
        known = c.lab("lk")
        c.g(RAX, "gui_target", field)
        c.jz(RAX, known)
        c.call("bw_unsc")
        c.address(RBX, "bw_elements")
        c.store(RBX, off, RAX)
        c.here(known)
    c.put(RBX, X, 0)
    c.put(RBX, Y, 0)
    c.put(RBX, SHOWN, 1)
    c.set(RAX, 0)
    c.sv(2, RAX)
    c.here(loop)
    c.set(RAX, 0)
    c.sv(1, RAX)
    c.set(RAX, 1)
    c.sv(0, RAX)
    c.here(inner)
    c.lv(RAX, 0)
    c.g(RCX, "bw_count")
    c.jr(RAX, RCX, NOT_LESS, done)
    c.call("bw_place")
    c.lv(RCX, 1)
    c.op("or", RCX, RAX)
    c.sv(1, RCX)
    c.lv(RAX, 0)
    c.op_n("add", RAX, 1)
    c.sv(0, RAX)
    c.jump(inner)
    c.here(done)
    c.lv(RAX, 2)
    c.op_n("add", RAX, 1)
    c.sv(2, RAX)
    c.lv(RCX, 1)
    c.jz(RCX, ok)
    c.jc(RAX, 8, LESS, loop)
    c.here(ok)
    c.leave(3)


def sort(c):
    """bw_order = elements 1 .. count-1 by depth, back to front; equal depths keep creation order."""
    loop, inner, put, done = c.lab("so"), c.lab("si"), c.lab("sp"), c.lab("sd")
    c.here("bw_sort")
    c.g(R8, "bw_count")
    c.address(R14, "bw_order")
    c.set(R9, 1)
    c.here(loop)
    c.jr(R9, R8, NOT_LESS, done)
    c.el(R10, R9)
    c.load(R10, R10, DEPTH)
    c.lea(R12, R9, -1)
    c.here(inner)
    c.jz(R12, put)
    c.lea(RCX, R12, -1)
    c.shift_left(RCX, 3)
    c.op("add", RCX, R14)
    c.load(R13, RCX)
    c.el(R15, R13)
    c.load(R15, R15, DEPTH)
    c.jr(R15, R10, NOT_GREATER, put)
    c.store(RCX, 8, R13)
    c.op_n("sub", R12, 1)
    c.jump(inner)
    c.here(put)
    c.mov(RCX, R12)
    c.shift_left(RCX, 3)
    c.op("add", RCX, R14)
    c.store(RCX, 0, R9)
    c.op_n("add", R9, 1)
    c.jump(loop)
    c.here(done)
    c.lea(R8, R8, -1)
    c.jc(R8, 0, NOT_LESS, done + "n")
    c.set(R8, 0)
    c.here(done + "n")
    c.sg("bw_order_n", R8)
    c.ret()


def clip_of(c):
    """rax = index -> rax = bw_clipblk {x0, y0, x1, y1}: the window cut down by each parent's rect (logical).
    bw_clip_in: rax = record -> bw_clipblk cut down by that element's own rect too; rax = bw_clipblk."""
    loop, done = c.lab("co"), c.lab("cod")
    c.here("bw_clip_of")
    c.address(RBX, "bw_elements")
    c.set(R12, 0)
    c.set(R13, 0)
    c.load(R14, RBX, W)
    c.load(R15, RBX, H)
    c.el(R8, RAX)
    c.load(R9, R8, PARENT)
    c.set(RDI, 8)                       # at most 8 parents deep
    c.here(loop)
    c.jc(R9, 0, NOT_GREATER, done)
    c.g(R10, "bw_count")
    c.jr(R9, R10, NOT_LESS, done)
    c.op_n("sub", RDI, 1)
    c.jump_if(LESS, done)
    c.el(R8, R9)
    c.mov(RAX, R8)
    c.call("bw_cut")
    c.load(R9, R8, PARENT)
    c.jump(loop)
    c.here(done)
    c.address(RAX, "bw_clipblk")
    for k, r in enumerate((R12, R13, R14, R15)):
        c.store(RAX, 8 * k, r)
    c.ret()
    # bw_cut: r12..r15 (x0 y0 x1 y1) cut down by the rect of the record in rax. Changes rcx, rdx.
    c.here("bw_cut")
    c.load(RCX, RAX, X)
    c.maxr(R12, RCX)
    c.load(RDX, RAX, W)
    c.op("add", RCX, RDX)
    c.minr(R14, RCX)
    c.load(RCX, RAX, Y)
    c.maxr(R13, RCX)
    c.load(RDX, RAX, H)
    c.op("add", RCX, RDX)
    c.minr(R15, RCX)
    c.ret()
    c.here("bw_clip_in")
    c.address(RSI, "bw_clipblk")
    for k, r in enumerate((R12, R13, R14, R15)):
        c.load(r, RSI, 8 * k)
    c.call("bw_cut")
    c.address(RAX, "bw_clipblk")
    for k, r in enumerate((R12, R13, R14, R15)):
        c.store(RAX, 8 * k, r)
    c.ret()


