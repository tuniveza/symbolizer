"""bitwin: brick's own window elements (buttons, texts, canvases, menus, tabs, input boxes, boxes, 3D views),
laid out, drawn and run by machine code brick writes itself. See docs/bitwin-contract.md ("bitwin runtime").

`add_all(a)` adds every `bw_` routine. It goes after runtime.add_all, wayland.add_all, paint.add_all and
(when the program has 3D views) glspace.add_all.

How it works:
- The element table `bw_elements` holds up to 256 records of 512 bytes. Element 0 is the window.
- Layout runs before every frame, in LOGICAL px (the numbers the program says). The resolved x, y, w, h
  (record fields 112-136) are logical px, so "the x of start" is the number the program used.
  Only drawing multiplies by `gui_scale / 120`, and pointer positions are divided by it on the way in.
- Drawing: the window background, a menu bar strip, every shown element in depth order (equal depth keeps
  creation order), each clipped to its parents, then any open menu's item list in front of everything.
  A frame is drawn only when something changed (bw_changed, an event that changes looks, any handler) or
  while a 3D view is animating.
- Events: wl_event with a timeout, so timers (bw_every) fire on time and the window stays responsive.
  Handlers run last in each event, so a handler may change anything or even wait (bw_wait) itself.
"""
import struct

from asm import (EQUAL, GREATER, LESS, NOT_EQUAL, NOT_GREATER, NOT_LESS, R8, R9, R10, R11, R12, R13, R14, R15,
                 RAX, RBX, RCX, RDI, RDX, RSI, RSP)

MAX_ELEMENTS = 256
ITEMS_MAX = 32

# ELEMENT record fields
KIND, NAME, PARENT, PAGE = 0, 8, 16, 24
XV, XU, YV, YU, WV, WU, HV, HU = 32, 40, 48, 56, 64, 72, 80, 88
OTHER, GAP = 96, 104
X, Y, W, H = 112, 120, 128, 136
DEPTH, FLAGS, TEXT, CLICK, ITEMS, PICKED, DATA, CHANGE = 144, 152, 160, 168, 176, 184, 192, 200
SHOWN, FLOW, HOVITEM = 208, 216, 224        # runtime fields: shown this frame, flow neighbour, hovered tab + 1
STYLE, HOVER, HOVER2, HOVERT = 256, 384, 392, 400
# STYLE fields
FILL, COL, COL2, DIR, TEX, TEXC, TEXS, TRANSP, RADIUS, BORDER, BORDERC, SHADOW, TCOL, TSIZE, TALIGN = range(0, 120, 8)
# flags
HIDDEN, DISABLED, HOVERED, PRESSED, FOCUSED, OPEN, HOVERSTYLE = 1, 2, 4, 8, 16, 32, 64
# kinds
WINDOW, BUTTON, CANVAS, MENU, TABS, TEXTK, GL, BOX, INPUT = range(1, 10)

# the default look: calm and dark
WIN_BG = 0x1C1F26
TEXT_COL = 0xE5E7EB
BTN_TOP, BTN_BOTTOM, BTN_BORDER, BTN_TEXT = 0x4B5466, 0x394050, 0x272C36, 0xF3F4F6
CANVAS_BG, CANVAS_BORDER = 0x101217, 0x2E333D
BOX_BG, BOX_BORDER = 0x262A33, 0x363C48
MENU_BG, MENU_LINE = 0x2A2E37, 0x3A404C
LIST_BG, LIST_BORDER = 0x2E333D, 0x454C59
TABS_BG, TABS_TEXT = 0x23272F, 0xAEB4BE
INPUT_BG, INPUT_BORDER = 0x14161B, 0x454C59
ACCENT = 0x5B8DEF
GL_BG = 0x0B0D10

MESSAGE_NO_DESKTOP = "This program opens a window, but there is no desktop here (no Wayland). Run it on the desktop.\n"
MESSAGE_TOO_MANY = "This program made too many window elements (255 is the most).\n"


def style(fill=0, col=0, col2=0, radius=0, border=0, borderc=0, shadow=0, tcol=0):
    fields = [0] * 16
    fields[0], fields[1], fields[2] = fill, col, col2
    fields[8], fields[9], fields[10], fields[11], fields[12] = radius, border, borderc, shadow, tcol
    return struct.pack("<16q", *fields)


class _C:
    """The assembler plus a few shorthands. Locals live at [rsp + 8k]; R10 and R11 are scratch."""

    def __init__(self, a, has_gl):
        self.a, self.has_gl = a, has_gl

    def __getattr__(self, name):
        return getattr(self.a, name)

    def lab(self, hint):
        return self.a.new_label("bw_" + hint)

    def here(self, name):
        self.a.label(name)

    def enter(self, n):
        self.a.op_n("sub", RSP, 8 * n)

    def leave(self, n):
        self.a.op_n("add", RSP, 8 * n)
        self.a.ret()

    def lv(self, reg, k):
        self.a.load(reg, RSP, 8 * k)

    def sv(self, k, reg):
        self.a.store(RSP, 8 * k, reg)

    def g(self, reg, label, off=0):
        self.a.address(reg, label)
        self.a.load(reg, reg, off)

    def sg(self, label, reg, off=0):
        self.a.address(R11, label)
        self.a.store(R11, off, reg)

    def gi(self, label, value):
        self.a.set(R10, value)
        self.sg(label, R10)

    def dirty(self):
        self.gi("bw_dirty", 1)

    def el(self, reg, idx):
        """reg = the record address of element number idx."""
        if reg != idx:
            self.a.mov(reg, idx)
        self.a.shift_left(reg, 9)
        self.a.address(R11, "bw_elements")
        self.a.op("add", reg, R11)

    def put(self, base, off, value):
        self.a.set(R10, value)
        self.a.store(base, off, R10)

    def jc(self, reg, n, cond, label):
        self.a.op_n("cmp", reg, n)
        self.a.jump_if(cond, label)

    def jr(self, r1, r2, cond, label):
        self.a.op("cmp", r1, r2)
        self.a.jump_if(cond, label)

    def jz(self, reg, label):
        self.a.op("test", reg, reg)
        self.a.jump_if(EQUAL, label)

    def jnz(self, reg, label):
        self.a.op("test", reg, reg)
        self.a.jump_if(NOT_EQUAL, label)

    def bit(self, reg, mask, tmp=R10):
        """Sets EQUAL when none of the mask's bits are set in reg."""
        self.a.mov(tmp, reg)
        self.a.op_n("and", tmp, mask)

    def valid(self, reg, bad, low=0):
        """Jump to bad unless low <= reg < bw_count."""
        self.jc(reg, low, LESS, bad)
        self.g(R10, "bw_count")
        self.jr(reg, R10, NOT_LESS, bad)

    def blk(self, *parts):
        """bw_blk = the parts (registers, or (0, n) for the number n); rax = its address."""
        self.a.address(R11, "bw_blk")
        for k, p in enumerate(parts):
            if isinstance(p, tuple):
                self.a.set(R10, p[1])
                p = R10
            self.a.store(R11, 8 * k, p)
        self.a.mov(RAX, R11)

    def tsize(self, reg, e):
        """reg = the element's text size (logical px)."""
        ok = self.lab("ts")
        self.a.load(reg, e, STYLE + TSIZE)
        self.jc(reg, 0, GREATER, ok)
        self.a.set(reg, 16)
        self.here(ok)

    def textof(self, reg, e):
        ok = self.lab("tx")
        self.a.load(reg, e, TEXT)
        self.jnz(reg, ok)
        self.a.address(reg, self.a.text(""))
        self.here(ok)

    def maxr(self, dst, src):
        self.a.op("cmp", src, dst)
        self.a.move_if(GREATER, dst, src)

    def minr(self, dst, src):
        self.a.op("cmp", src, dst)
        self.a.move_if(LESS, dst, src)

    def muldiv(self, n):
        """rax = rax x rcx / n (signed). Changes rdx, r8."""
        self.a.multiply(RAX, RCX)
        self.a.sign_extend()
        self.a.set(R8, n)
        self.a.divide(R8, signed=True)

    def handler(self, reg):
        """Run the handler whose address is in reg (if any), then redraw."""
        skip = self.lab("nohandler")
        self.jz(reg, skip)
        self.a.call_reg(reg)
        self.dirty()
        self.here(skip)

    def flag_on(self, e, mask):
        self.a.load(R10, e, FLAGS)
        self.a.op_n("or", R10, mask)
        self.a.store(e, FLAGS, R10)

    def flag_off(self, e, mask):
        self.a.load(R10, e, FLAGS)
        self.a.op_n("and", R10, ~mask)
        self.a.store(e, FLAGS, R10)

    def lighten(self, reg, shift=3):
        """reg (a colour) moves 1/8 (shift 3) or 1/4 (shift 2) of the way to white."""
        self.a.mov(R10, reg)
        self.a.op_n("xor", R10, 0xFFFFFF)
        self.a.shift_right(R10, shift)
        self.a.op_n("and", R10, {2: 0x3F3F3F, 3: 0x1F1F1F, 4: 0x0F0F0F}[shift])
        self.a.op("add", reg, R10)

    def darken(self, reg):
        """reg (a colour) gets a quarter darker."""
        self.a.mov(R10, reg)
        self.a.shift_right(R10, 2)
        self.a.op_n("and", R10, 0x3F3F3F)
        self.a.op("sub", reg, R10)

    def say_exit(self, message):
        self.a.address(RAX, self.a.text(message))
        self.a.call("write_text")
        self.a.set(RAX, 60)
        self.a.set(RDI, 1)
        self.a.syscall()


def add_all(a):
    has_gl = "gl_render" in a.labels
    c = _C(a, has_gl)
    for name, size in (("gui_target", 32), ("gui_clip", 32), ("gui_scale", 8)):
        a.space.setdefault(name, size)
    a.space["bw_elements"] = MAX_ELEMENTS * 512
    for name in ("bw_count", "bw_dirty", "bw_open_now", "bw_closed", "bw_mouse_x", "bw_mouse_y", "bw_key",
                 "bw_last", "bw_chosen", "bw_on_close", "bw_on_key", "bw_on_move", "bw_on_resize", "bw_every",
                 "bw_every_ms", "bw_next_tick", "bw_hover", "bw_press", "bw_focus", "bw_menu", "bw_menu_item",
                 "bw_clicked", "bw_click_count", "bw_order_n"):
        a.space[name] = 8
    a.space["bw_order"] = 8 * MAX_ELEMENTS
    for name, size in (("bw_blk", 64), ("bw_sty", 128), ("bw_sty2", 128), ("bw_ssty", 128), ("bw_tsty", 128),
                       ("bw_clipblk", 32), ("bw_rclip", 32), ("bw_line", 8 + 1024 + 8), ("bw_ml", 64)):
        a.space[name] = size
    a.data["bw_bar_style"] = style(1, MENU_BG)
    a.data["bw_barline_style"] = style(1, MENU_LINE)
    a.data["bw_list_style"] = style(1, LIST_BG, radius=6, border=1, borderc=LIST_BORDER, shadow=4)
    a.data["bw_pick_style"] = style(1, ACCENT, radius=4)
    a.data["bw_accent_style"] = style(1, ACCENT)
    for routine in (scaling, init, depth_range, new, elem, find, set_text, add_item, item_handler, depth_moves,
                    shapes, small_ones, open_window, measure, sub, lines, fit, flow_of, place, layout, sort,
                    clip_of, draw_elem, label, draw_input, draw_shapes, draw_gl, draw_tabs, tab_at, menu_geom,
                    draw_menu_list, frame, hit, events, edit, splice, loop):
        routine(c)


# ---- scaling: logical px -> real px ----

def scaling(c):
    a = c
    # bw_sc: rax = rax x scale / 120. Changes only rdx, r11.
    ok = c.lab("sc")
    c.here("bw_sc")
    c.g(R11, "gui_scale")
    c.jnz(R11, ok)
    c.set(R11, 120)
    c.here(ok)
    c.multiply(RAX, R11)
    c.sign_extend()
    c.set(R11, 120)
    c.divide(R11, signed=True)
    c.ret()
    # bw_unsc: rax = rax x 120 / scale, rounded (real px -> logical). Changes only rdx, r11.
    ok = c.lab("usc")
    c.here("bw_unsc")
    c.g(R11, "gui_scale")
    c.jnz(R11, ok)
    c.set(R11, 120)
    c.here(ok)
    c.multiply_n(RAX, RAX, 120)
    c.push(R11)
    c.shift_right(R11, 1)
    c.op("add", RAX, R11)               # rounded to the nearest
    c.pop(R11)
    c.sign_extend()
    c.divide(R11, signed=True)
    c.ret()
    # bw_sblk: bw_blk fields 0-3 (x, y, w, h) logical -> real, edges kept exact. Changes rax, rcx, rdx, r8, r9, r11.
    c.here("bw_sblk")
    c.address(R9, "bw_blk")
    for pos, size in ((0, 16), (8, 24)):
        c.load(RAX, R9, pos)
        c.load(R8, R9, size)
        c.op("add", R8, RAX)
        c.call("bw_sc")
        c.mov(RCX, RAX)
        c.mov(RAX, R8)
        c.call("bw_sc")
        c.op("sub", RAX, RCX)
        c.store(R9, size, RAX)
        c.store(R9, pos, RCX)
    c.ret()
    # bw_sfield: rcx = offset in bw_blk: that field logical -> real. Changes rax, rdx, r9, r11.
    c.here("bw_sfield")
    c.address(R9, "bw_blk")
    c.op("add", R9, RCX)
    c.load(RAX, R9)
    c.call("bw_sc")
    c.store(R9, 0, RAX)
    c.ret()
    # bw_pbox / bw_pell: paint_box / paint_ellipse of bw_blk (logical rect, style already real)
    for name, target in (("bw_pbox", "paint_box"), ("bw_pell", "paint_ellipse")):
        c.here(name)
        c.call("bw_sblk")
        c.address(RAX, "bw_blk")
        c.jump(target)
    # bw_ptext: paint_text of bw_blk {x, y, text, colour, size, transparency}, all logical
    c.here("bw_ptext")
    for off in (0, 8, 32):
        c.set(RCX, off)
        c.call("bw_sfield")
    c.address(RAX, "bw_blk")
    c.jump("paint_text")
    # bw_scale_style: rax = a STYLE block, its px fields logical -> real, in place
    c.here("bw_scale_style")
    c.mov(R9, RAX)
    for off, empty, at_least_one in ((TEXS, 8, False), (RADIUS, 0, False), (BORDER, 0, True), (SHADOW, 0, True)):
        skip, keep = c.lab("ss"), c.lab("ssk")
        c.load(RAX, R9, off)
        if empty:
            c.jnz(RAX, keep)
            c.set(RAX, empty)
            c.here(keep)
        else:
            c.jz(RAX, skip)
        c.call("bw_sc")
        if at_least_one:
            c.jc(RAX, 0, GREATER, skip + "o")
            c.set(RAX, 1)
            c.here(skip + "o")
        c.store(R9, off, RAX)
        c.here(skip)
    c.ret()
    # bw_style_copy: rax = a STYLE -> rax = bw_sty2, a scaled copy
    c.here("bw_style_copy")
    c.mov(RSI, RAX)
    c.address(RDI, "bw_sty2")
    c.set(RCX, 128)
    c.copy_bytes()
    c.address(RAX, "bw_sty2")
    c.call("bw_scale_style")
    c.address(RAX, "bw_sty2")
    c.ret()
    # bw_sclip: rax = a logical clip block {x0, y0, x1, y1} -> paint_clip with it in real px
    c.here("bw_sclip")
    c.mov(RSI, RAX)
    c.address(RDI, "bw_rclip")
    for off in (0, 8, 16, 24):
        c.load(RAX, RSI, off)
        c.call("bw_sc")
        c.store(RDI, off, RAX)
    c.mov(RAX, RDI)
    c.jump("paint_clip")


# ---- the table ----

def init(c):
    done = c.lab("init_done")
    c.here("bw_init")
    c.g(RAX, "bw_count")
    c.jnz(RAX, done)
    c.gi("bw_count", 1)
    c.set(RAX, -1)
    for v in ("bw_hover", "bw_press", "bw_focus", "bw_menu", "bw_menu_item", "bw_clicked"):
        c.sg(v, RAX)
    c.address(RAX, c.text(""))
    c.sg("bw_chosen", RAX)
    c.address(RDI, "bw_elements")
    c.store(RDI, TEXT, RAX)
    for off, value in ((KIND, WINDOW), (WV, 800), (HV, 600), (W, 800), (H, 600), (SHOWN, 1),
                       (STYLE + FILL, 1), (STYLE + COL, WIN_BG), (STYLE + TCOL, TEXT_COL)):
        c.put(RDI, off, value)
    c.here(done)
    c.ret()


def depth_range(c):
    """-> rax = the biggest depth, rcx = the smallest (0 counts too)."""
    loop, done = c.lab("dr"), c.lab("drd")
    c.here("bw_depth_range")
    c.set(RAX, 0)
    c.set(RCX, 0)
    c.g(R8, "bw_count")
    c.set(RDX, 1)
    c.here(loop)
    c.jr(RDX, R8, NOT_LESS, done)
    c.el(R9, RDX)
    c.load(R10, R9, DEPTH)
    c.maxr(RAX, R10)
    c.minr(RCX, R10)
    c.op_n("add", RDX, 1)
    c.jump(loop)
    c.here(done)
    c.ret()


def new(c):
    """rax = kind, rcx = name -> rax = the new element's number."""
    a = c
    ok, loop, done, notmenu, nxt, finish = (c.lab(h) for h in ("nok", "nl", "nd", "nnm", "nn", "nf"))
    c.here("bw_new")
    c.enter(6)                          # 0 kind, 1 name, 2 index, 3 record, 4 flow neighbour, 5 last menu
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.call("bw_init")
    c.g(RAX, "bw_count")
    c.jc(RAX, MAX_ELEMENTS, LESS, ok)
    c.say_exit(MESSAGE_TOO_MANY)
    c.here(ok)
    c.sv(2, RAX)
    c.lea(RCX, RAX, 1)
    c.sg("bw_count", RCX)
    c.call("bw_depth_range")
    c.lea(R12, RAX, 1)
    c.lv(RAX, 2)
    c.el(RDI, RAX)
    c.sv(3, RDI)
    c.store(RDI, DEPTH, R12)
    c.lv(RAX, 0)
    c.store(RDI, KIND, RAX)
    c.lv(RAX, 1)
    c.store(RDI, NAME, RAX)
    c.address(RAX, c.text(""))
    c.store(RDI, TEXT, RAX)
    # the elements made before: r13 = the last that isn't a menu, r14 = the last menu
    c.set(R13, 0)
    c.set(R14, 0)
    c.set(R12, 1)
    c.lv(RBX, 2)
    c.here(loop)
    c.jr(R12, RBX, NOT_LESS, done)
    c.el(R9, R12)
    c.load(R10, R9, KIND)
    c.jc(R10, MENU, NOT_EQUAL, notmenu)
    c.mov(R14, R12)
    c.jump(nxt)
    c.here(notmenu)
    c.mov(R13, R12)
    c.here(nxt)
    c.op_n("add", R12, 1)
    c.jump(loop)
    c.here(done)
    c.sv(5, R14)
    c.jnz(R13, done + "f")
    c.mov(R13, R14)
    c.here(done + "f")
    c.sv(4, R13)

    kinds = {k: c.lab(f"kind{k}") for k in (BUTTON, CANVAS, MENU, TABS, TEXTK, GL, BOX, INPUT)}
    c.lv(RAX, 0)
    for k, lab in kinds.items():
        c.jc(RAX, k, EQUAL, lab)
    c.jump(finish)

    def flow(fits=True):
        c.lv(RAX, 4)
        c.store(RDI, FLOW, RAX)
        c.put(RDI, XU, 9)
        c.put(RDI, YU, 9)

    def fields(pairs):
        for off, value in pairs:
            c.put(RDI, off, value)

    c.here(kinds[BUTTON])
    flow()
    fields([(WU, 7), (HU, 7), (STYLE + FILL, 2), (STYLE + COL, BTN_TOP), (STYLE + COL2, BTN_BOTTOM),
            (STYLE + RADIUS, 6), (STYLE + BORDER, 1), (STYLE + BORDERC, BTN_BORDER), (STYLE + TCOL, BTN_TEXT)])
    c.jump(finish)

    c.here(kinds[CANVAS])
    flow()
    fields([(WV, 300), (HV, 200), (STYLE + FILL, 1), (STYLE + COL, CANVAS_BG), (STYLE + BORDER, 1),
            (STYLE + BORDERC, CANVAS_BORDER), (STYLE + TCOL, TEXT_COL)])
    c.set(RCX, 16 + 16 * 64)
    c.call("alloc")
    c.lv(RDI, 3)
    c.store(RDI, DATA, RAX)
    c.put(RAX, 8, 16)
    c.jump(finish)

    c.here(kinds[MENU])
    first = c.lab("firstmenu")
    fields([(WU, 7), (HU, 7), (STYLE + FILL, 1), (STYLE + COL, MENU_BG), (STYLE + TCOL, TEXT_COL)])
    c.lv(RAX, 5)
    c.jz(RAX, finish)                   # the first menu: at 0 0
    c.store(RDI, OTHER, RAX)            # later ones: right of the menu before
    c.put(RDI, XU, 4)
    c.put(RDI, YU, 6)
    c.jump(finish)

    c.here(kinds[TABS])
    fields([(WV, 100), (WU, 1), (HU, 7), (STYLE + FILL, 1), (STYLE + COL, TABS_BG), (STYLE + TCOL, TABS_TEXT)])
    c.lv(RAX, 5)
    c.jz(RAX, finish)                   # under the menu bar, if there is one
    c.store(RDI, OTHER, RAX)
    c.put(RDI, YU, 4)
    c.jump(finish)

    c.here(kinds[TEXTK])
    flow()
    fields([(WU, 7), (HU, 7), (STYLE + TCOL, TEXT_COL), (STYLE + TALIGN, 1)])
    c.jump(finish)

    c.here(kinds[GL])
    flow()
    fields([(WV, 300), (HV, 300)])
    if c.has_gl:
        c.call("gl_new_view")
        c.lv(RDI, 3)
        c.store(RDI, DATA, RAX)
    else:
        fields([(STYLE + FILL, 1), (STYLE + COL, GL_BG)])
    c.jump(finish)

    c.here(kinds[BOX])
    flow()
    fields([(WV, 200), (HV, 150), (STYLE + FILL, 1), (STYLE + COL, BOX_BG), (STYLE + RADIUS, 8),
            (STYLE + BORDER, 1), (STYLE + BORDERC, BOX_BORDER), (STYLE + TCOL, TEXT_COL)])
    c.jump(finish)

    c.here(kinds[INPUT])
    flow()
    fields([(WV, 220), (HU, 7), (STYLE + FILL, 1), (STYLE + COL, INPUT_BG), (STYLE + RADIUS, 5),
            (STYLE + BORDER, 1), (STYLE + BORDERC, INPUT_BORDER), (STYLE + TCOL, TEXT_COL), (STYLE + TALIGN, 1)])

    c.here(finish)
    c.dirty()
    c.lv(RAX, 2)
    c.leave(6)


def elem(c):
    c.here("bw_elem")
    c.shift_left(RAX, 9)
    c.address(R11, "bw_elements")
    c.op("add", RAX, R11)
    c.ret()


def find(c):
    loop, nxt, found, none = c.lab("fl"), c.lab("fn"), c.lab("ff"), c.lab("fx")
    c.here("bw_find")
    c.enter(2)                          # 0 name, 1 index
