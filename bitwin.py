def measure(c):
    """rax = text (0 = empty), rcx = size (logical px) -> rax = width, rcx = height (logical px, rounded up)."""
    has = c.lab("ms")
    c.here("bw_measure")
    c.jnz(RAX, has)
    c.address(RAX, c.text(""))
    c.here(has)
    c.jc(RCX, 0, GREATER, has + "z")
    c.set(RCX, 16)
    c.here(has + "z")
    c.push(RAX)
    c.mov(RAX, RCX)
    c.call("bw_sc")
    c.mov(RCX, RAX)
    c.pop(RAX)
    c.call("paint_measure")
    c.push(RCX)
    c.call("bw_unsc_up")
    c.pop(RCX)
    c.push(RAX)
    c.mov(RAX, RCX)
    c.call("bw_unsc_up")
    c.mov(RCX, RAX)
    c.pop(RAX)
    c.ret()
    # bw_unsc_up: rax real px -> logical, rounded up. Changes rdx, r11.
    ok = c.lab("usu")
    c.here("bw_unsc_up")
    c.g(R11, "gui_scale")
    c.jnz(R11, ok)
    c.set(R11, 120)
    c.here(ok)
    c.multiply_n(RAX, RAX, 120)
    c.op("add", RAX, R11)
    c.op_n("sub", RAX, 1)
    c.sign_extend()
    c.divide(R11, signed=True)
    c.ret()


def sub(c):
    """rax = text, rcx = from, rdx = to -> rax = bw_line, a text holding those bytes (at most 1024)."""
    ok = c.lab("sb")
    c.here("bw_sub")
    c.jnz(RAX, ok)
    c.address(RAX, c.text(""))
    c.here(ok)
    c.load(R8, RAX)
    c.minr(RDX, R8)
    c.minr(RCX, RDX)
    c.set(R9, 0)
    c.maxr(RCX, R9)
    c.op("sub", RDX, RCX)
    c.maxr(RDX, R9)
    c.set(R9, 1024)
    c.minr(RDX, R9)
    c.lea(RSI, RAX, 8)
    c.op("add", RSI, RCX)
    c.address(RDI, "bw_line")
    c.store(RDI, 0, RDX)
    c.op_n("add", RDI, 8)
    c.mov(RCX, RDX)
    c.copy_bytes()
    c.set(RCX, 0)
    c.store_byte(RDI, 0, RCX)
    c.address(RAX, "bw_line")
    c.ret()


def lines(c):
    """rax = record, rcx = 0 measure / 1 draw, rdx = width to wrap in (-1 = no wrapping)
    -> rax = lines, rcx = widest line, rdx = line height. Drawing uses bw_sty's colours."""
    outer, scan, sp, wd, emit, done, nodraw = (c.lab(h) for h in ("lo", "ls", "lsp", "lwd", "le", "ld", "lnd"))
    c.here("bw_lines")
    c.enter(15)     # 14 candidate, 0 e, 1 mode, 2 W, 3 text, 4 L, 5 pos, 6 best, 7 k, 8 lines, 9 maxw, 10 lineh, 11 y, 12 size, 13 linew
    c.sv(0, RAX)
    c.sv(1, RCX)
    c.jc(RDX, 0, NOT_LESS, outer + "w")
    c.set(RDX, 1 << 40)
    c.here(outer + "w")
    c.sv(2, RDX)
    c.mov(RBX, RAX)
    c.textof(RCX, RBX)
    c.sv(3, RCX)
    c.load(RCX, RCX)
    c.sv(4, RCX)
    c.tsize(RCX, RBX)
    c.sv(12, RCX)
    c.load(RCX, RBX, Y)
    c.sv(11, RCX)
    c.set(RAX, 0)
    for k in (5, 8, 9):
        c.sv(k, RAX)
    c.lv(RCX, 12)
    c.call("bw_measure")
    c.sv(10, RCX)
    c.here(outer)
    c.lv(RAX, 5)
    c.lv(RCX, 4)
    c.jr(RAX, RCX, NOT_LESS, done)
    c.set(RCX, -1)
    c.sv(6, RCX)
    c.sv(7, RAX)
    c.here(scan)
    c.lv(R12, 7)
    c.lv(R13, 3)
    c.lv(R14, 4)
    c.here(sp)                          # skip spaces
    c.jr(R12, R14, NOT_LESS, wd + "e")
    c.lea(R10, R13, 8)
    c.op("add", R10, R12)
    c.load_byte(RAX, R10)
    c.jc(RAX, 32, NOT_EQUAL, wd)
    c.op_n("add", R12, 1)
    c.jump(sp)
    c.here(wd)                          # then a word
    c.jr(R12, R14, NOT_LESS, wd + "e")
    c.lea(R10, R13, 8)
    c.op("add", R10, R12)
    c.load_byte(RAX, R10)
    c.jc(RAX, 32, EQUAL, wd + "e")
    c.jc(RAX, 10, EQUAL, wd + "e")
    c.op_n("add", R12, 1)
    c.jump(wd)
    c.here(wd + "e")
    c.sv(14, R12)                       # the candidate end of this line
    c.lv(RAX, 3)
    c.lv(RCX, 5)
    c.mov(RDX, R12)
    c.call("bw_sub")
    c.lv(RCX, 12)
    c.call("bw_measure")
    c.lv(RCX, 6)
    c.jc(RCX, -1, EQUAL, wd + "ok")
    c.lv(RCX, 2)
    c.jr(RAX, RCX, GREATER, emit)       # this word doesn't fit any more
    c.here(wd + "ok")
    c.lv(R12, 14)
    c.sv(6, R12)
    c.sv(7, R12)
    c.sv(13, RAX)
    c.lv(R14, 4)
    c.jr(R12, R14, NOT_LESS, emit)
    c.lv(R13, 3)
    c.lea(R10, R13, 8)
    c.op("add", R10, R12)
    c.load_byte(RAX, R10)
    c.jc(RAX, 10, EQUAL, emit)
    c.jump(scan)

    c.here(emit)
    c.lv(RAX, 8)
    c.op_n("add", RAX, 1)
    c.sv(8, RAX)
    c.lv(RAX, 9)
    c.lv(RCX, 13)
    c.maxr(RAX, RCX)
    c.sv(9, RAX)
    c.lv(RAX, 1)
    c.jz(RAX, nodraw)
    c.lv(RAX, 3)
    c.lv(RCX, 5)
    c.lv(RDX, 6)
    c.call("bw_sub")
    c.mov(R12, RAX)                     # the line's text
    c.lv(RBX, 0)
    c.load(R13, RBX, X)
    c.address(R9, "bw_sty")
    c.load(R8, R9, TALIGN)
    c.jc(R8, 1, EQUAL, nodraw + "x")
