    a.jump_if(EQUAL, linear)
    a.op_n("cmp", RAX, 3)
    a.jump_if(EQUAL, radial)
    a.op_n("cmp", RAX, 1)
    a.jump_if(NOT_EQUAL, alpha)
    p.ld(RAX, "c1")
    a.address(RDI, "paint_rowc")
