    a.jump_if(NOT_LESS, columns)
    p.ld(RDX, "v")
    p.ld(R8, "H")
    a.op_n("sub", R8, 1)
    a.op_n("cmp", RBX, 0)
    down = p.label("fill_down")
    a.jump_if(EQUAL, down)
    a.mov(RAX, R8)
    a.op("sub", RAX, RDX)
