"""paint.py: brick's own painter. Machine-code routines that draw into `gui_target` inside `gui_clip`.

The routines and the STYLE block are in docs/bitwin-contract.md. tests/paint_reference.py is the same
painter in plain Python (the same sums, so the pixels match exactly); read it to see the rules plainly.

How a box or ellipse is painted, one row at a time:
  1. fill: the colours of the row go into a row buffer (solid; a linear gradient from a table made once per
     call, so no dividing per pixel; radial: a distance per pixel, colour from a 256-entry table),
     with alpha 255 (or 0 when there is no fill);
  2. texture: marks (0..255) in the texture colour over the fill, counted along the row without dividing;
  3. shape: border bands, and for each pixel near a round edge a signed distance d (decimal):
     coverage = 0.5 - d, border = d within the border width; both soft over one pixel (anti-aliased);
  4. blend the row into the target: alpha x (255 - transparency); whole rows that are solid are copied.
The shadow is painted first: a soft dark copy of the shape, `shadow` px down and right, as wide as 2 x shadow.

Lines are anti-aliased (distance to the segment, round ends), from pixel centre to pixel centre.
Triangles are solid with the top-left rule: triangles sharing an edge leave no gap and paint no pixel twice.
Text uses font.py ("brick letters"): the nearest baked size, scaled with bilinear sampling.

Inside paint, r15 points at the variables (paint_v) and r14 at the decimal constants (paint_k).
"""
import struct

import font
from asm import (ABOVE, EQUAL, GREATER, LESS, NOT_NEGATIVE, NOT_ABOVE, NOT_BELOW, NOT_EQUAL, NOT_GREATER,
                 NOT_LESS, R8, R9, R10, R11, R12, R13, R14, R15, RAX, RBP, RBX, RCX, RDI, RDX, RSI)

MAXW = 16384                 # widest / tallest area painted at once (the row buffers)
LIM = 1 << 28                # positions are kept within +-LIM, sizes within 2 x LIM
SHADOW_ALPHA = 110           # how dark the middle of a shadow is (0..255)
LANES = 0xFF00FF00FF         # three 16-bit lanes: blue at bit 0, green at 16, red at 32
HALF_LANES = 0x8000800080
X0, X1, X2, X3, X4, X5, X6, X7, X8, X9, X10, X11, X12, X13, X14, X15 = range(16)
STYLE_FIELDS = [("fill", 0, False), ("c1", 8, True), ("c2", 16, True), ("dir", 24, False), ("tex", 32, False),
                ("tcol", 40, True), ("tsize", 48, False), ("transp", 56, False), ("rad", 64, False),
                ("bw", 72, False), ("bcol", 80, True), ("shadow", 88, False)]


class Writer:
    """Small helpers for writing the routines."""

    def __init__(self, a):
        self.a = a
        self.vars = {}
        self.consts = {}

    def v(self, name):
        if name not in self.vars:
            self.vars[name] = 8 * len(self.vars)
        return self.vars[name]

    def ld(self, reg, name):
        self.a.load(reg, R15, self.v(name))

    def st(self, name, reg):
        self.a.store(R15, self.v(name), reg)

    def ldx(self, xmm, name):
        self.a.load_decimal(xmm, R15, self.v(name))

    def stx(self, name, xmm):
        self.a.store_decimal(R15, self.v(name), xmm)

    def k(self, xmm, value):
        """xmm = a fixed decimal (or "abs": the mask that clears the sign)."""
        if value not in self.consts:
            self.consts[value] = 8 * len(self.consts)
        self.a.load_decimal(xmm, R14, self.consts[value])

    def const_bytes(self):
        out = bytearray(8 * len(self.consts))
        for value, at in self.consts.items():
            out[at:at + 8] = struct.pack("<Q", 0x7FFFFFFFFFFFFFFF) if value == "abs" else struct.pack("<d", value)
        return bytes(out)

    def label(self, hint):
        return self.a.new_label("paint_" + hint)

    def enter(self):
        self.a.address(R15, "paint_v")
        self.a.address(R14, "paint_k")

    # ---- whole numbers ----

    def imin(self, dst, src):
        self.a.op("cmp", dst, src)
        self.a.move_if(GREATER, dst, src)

    def imax(self, dst, src):
        self.a.op("cmp", dst, src)
        self.a.move_if(LESS, dst, src)

    def imin_n(self, dst, n, tmp):
        self.a.set(tmp, n)
        self.imin(dst, tmp)

    def imax_n(self, dst, n, tmp):
        self.a.set(tmp, n)
        self.imax(dst, tmp)

    def clamp_n(self, reg, lo, hi, tmp):
        self.imax_n(reg, lo, tmp)
        self.imin_n(reg, hi, tmp)

    def div255(self, reg, tmp):
        """reg = reg / 255 rounded (reg from 0 to 65025)."""
        a = self.a
        a.op_n("add", reg, 128)
        a.mov(tmp, reg)
        a.shift_right(tmp, 8)
        a.op("add", reg, tmp)
        a.shift_right(reg, 8)

    def float_of(self, xmm, reg):
        self.a.decimal_clear(xmm)          # CVTSI2SD keeps the old upper half: without this, each pixel waits
        self.a.whole_to_decimal(xmm, reg)  # for the sums of the one before

    def var_float(self, xmm, name, tmp=RAX):
        self.ld(tmp, name)
        self.float_of(xmm, tmp)

    def centre(self, xmm, reg):
        """xmm = float(reg) + 0.5: the middle of pixel reg."""
        self.float_of(xmm, reg)
        self.addk(xmm, 0.5)

    def addk(self, xmm, value):
        self.k(X15, value)
        self.a.decimal_maths("add", xmm, X15)

    def subk(self, xmm, value):
        self.k(X15, value)
        self.a.decimal_maths("sub", xmm, X15)

    def mulk(self, xmm, value):
        self.k(X15, value)
        self.a.decimal_maths("mul", xmm, X15)

    def opv(self, name, xmm, var):
        """xmm (op)= the decimal variable var."""
        self.ldx(X15, var)
        self.a.decimal_maths(name, xmm, X15)

    def to_alpha(self, reg, xmm):
        """reg = int(xmm) kept within 0..255."""
        self.a.decimal_to_whole(reg, xmm)
        self.clamp_n(reg, 0, 255, RCX if reg != RCX else RDX)

    # ---- colours packed in lanes ----

    def spread(self, reg, t1, t2):
        """0x00RRGGBB -> red, green, blue in 16-bit lanes."""
        a = self.a
        a.mov(t1, reg)
        a.op_n("and", t1, 0xFF00)
        a.shift_left(t1, 8)
        a.mov(t2, reg)
        a.op_n("and", t2, 0xFF0000)
        a.shift_left(t2, 16)
        a.op_n("and", reg, 0xFF)
        a.op("or", reg, t1)
        a.op("or", reg, t2)

    def unspread(self, reg, t1, t2):
        """Each lane / 255 rounded, then packed back to 0x00RRGGBB."""
        a = self.a
        a.set(t2, LANES)
        a.set(t1, HALF_LANES)
        a.op("add", reg, t1)
        a.mov(t1, reg)
        a.shift_right(t1, 8)
        a.op("and", t1, t2)
        a.op("add", reg, t1)
        a.shift_right(reg, 8)
        a.op("and", reg, t2)
        a.mov(t1, reg)
        a.shift_right(t1, 8)
        a.op_n("and", t1, 0xFF00)
        a.mov(t2, reg)
        a.shift_right(t2, 16)
        a.op_n("and", t2, 0xFF0000)
        a.op_n("and", reg, 0xFF)
        a.op("or", reg, t1)
        a.op("or", reg, t2)

    def mix(self, spread_src=False):
        """rax = colour rax over colour r8 at alpha rdx (1..254); rax may already be spread. Changes rcx, r8, r9."""
        a = self.a
        if not spread_src:
            self.spread(RAX, RCX, R9)
        a.multiply(RAX, RDX)
        self.spread(R8, RCX, R9)
        a.set(RCX, 255)
        a.op("sub", RCX, RDX)
        a.multiply(R8, RCX)
        a.op("add", RAX, R8)
        self.unspread(RAX, RCX, R9)

    def row_address(self, dst, y_reg, x_reg, tmp):
        """dst = the address of pixel (x, y) of the target."""
        a = self.a
        self.ld(dst, "stride")
        a.multiply(dst, y_reg)
        a.mov(tmp, x_reg)
        a.shift_left(tmp, 2)
        a.op("add", dst, tmp)
        self.ld(tmp, "base")
        a.op("add", dst, tmp)

    def opacity(self, src_reg, tmp):
        """'op' = 255 - transparency (kept within 0..255) from src_reg; jumps nowhere. Leaves op in src_reg."""
        a = self.a
        self.clamp_n(src_reg, 0, 255, tmp)
        a.set(tmp, 255)
        a.op("sub", tmp, src_reg)
        a.mov(src_reg, tmp)
        self.st("op", src_reg)


# ---- the clip ----

def clip_routines(p):
    a = p.a
    a.label("paint_clip_all")
    a.address(RSI, "gui_target")
    a.load(RCX, RSI, 8)
    a.load(RDX, RSI, 16)
    a.set(R8, 0)
    a.set(R9, 0)
    a.jump("paint_clip_store")

    a.label("paint_clip")
    a.address(RSI, "gui_target")
    a.load(RCX, RSI, 8)
    a.load(RDX, RSI, 16)
    a.load(R8, RAX, 0)
    a.load(R9, RAX, 8)
    a.load(R10, RAX, 16)
    a.load(R11, RAX, 24)
    a.set(RAX, 0)
    p.imax(R8, RAX)
    p.imax(R9, RAX)
    p.imin(RCX, R10)
    p.imin(RDX, R11)
    a.label("paint_clip_store")
    a.address(RDI, "gui_clip")
    a.store(RDI, 0, R8)
    a.store(RDI, 8, R9)
    a.store(RDI, 16, RCX)
    a.store(RDI, 24, RDX)
    a.address(RDI, "paint_v")
    a.set(RAX, 1)
    a.store(RDI, p.v("clipset"), RAX)
    a.ret()

    # the clip actually used: the clip (or the whole target if never set), cut to the target and MAXW
    a.label("paint_eclip")
    a.address(RSI, "gui_target")
    a.load(RAX, RSI, 0)
    p.st("base", RAX)
    a.load(RCX, RSI, 8)
    a.load(RDX, RSI, 16)
    a.load(RAX, RSI, 24)
    p.st("stride", RAX)
    a.set(R10, 0)
    a.set(R11, 0)
    a.mov(R12, RCX)
    a.mov(R13, RDX)
    p.ld(RAX, "clipset")
    a.op("test", RAX, RAX)
    whole = p.label("whole")
    a.jump_if(EQUAL, whole)
    a.address(RSI, "gui_clip")
    a.load(R10, RSI, 0)
    a.load(R11, RSI, 8)
    a.load(R12, RSI, 16)
    a.load(R13, RSI, 24)
    a.label(whole)
    a.set(RAX, 0)
    p.imax(R10, RAX)
    p.imax(R11, RAX)
    p.imin(R12, RCX)
    p.imin(R13, RDX)
    p.imin_n(R12, MAXW, RAX)
    p.imin_n(R13, MAXW, RAX)
    p.ld(RAX, "base")
    a.op("test", RAX, RAX)
    a.move_if(EQUAL, R12, R10)          # no pixels at all: nothing is drawn
    p.st("ex0", R10)
    p.st("ey0", R11)
    p.st("ex1", R12)
    p.st("ey1", R13)
    a.ret()


# ---- boxes and ellipses ----

def lerp_routine(p):
    """paint_lerp: rax = colour 1, rcx = colour 2, rdx = n, r8 = d -> rax = colour n/d of the way.
    Changes rbx, rcx, rdx, rsi, rdi, r9, r10, r11."""
    a = p.a
    a.label("paint_lerp")
    a.op("test", R8, R8)
    done = p.label("lerp_c1")
    a.jump_if(NOT_GREATER, done)
    a.mov(RDI, RAX)
    a.mov(RSI, RCX)
    a.mov(RBX, RDX)
    a.mov(R9, R8)
    a.op("sub", R9, RBX)                # d - n
    a.set(R10, 0)
    for shift in (16, 8, 0):
        a.mov(RAX, RDI)
        if shift:
            a.shift_right(RAX, shift)
        a.op_n("and", RAX, 255)
        a.multiply(RAX, R9)
        a.mov(R11, RSI)
        if shift:
            a.shift_right(R11, shift)
        a.op_n("and", R11, 255)
        a.multiply(R11, RBX)
        a.op("add", RAX, R11)
        a.mov(R11, R8)
        a.shift_right(R11, 1)
        a.op("add", RAX, R11)
        a.set(RDX, 0)
        a.divide(R8)
        a.shift_left(R10, 8)
        a.op("or", R10, RAX)
    a.mov(RAX, R10)
    a.ret()
    a.label(done)
    a.ret()


def shape_routine(p):
    a = p.a
    done = "paint_shape_done"
    for name, shape in (("paint_box", 0), ("paint_ellipse", 1)):
        a.label(name)
        p.enter()
        a.set(RCX, shape)
        p.st("shape", RCX)
        a.jump("paint_shape")
    a.label("paint_shape")
    a.mov(RSI, RAX)
    a.load(RAX, RSI, 0)
    a.load(RCX, RSI, 8)
    a.load(RDX, RSI, 16)
    a.load(R8, RSI, 24)
    a.load(RBX, RSI, 32)
    a.op("test", RDX, RDX)
    a.jump_if(NOT_GREATER, done)
    a.op("test", R8, R8)
    a.jump_if(NOT_GREATER, done)
    a.op("test", RBX, RBX)
    a.jump_if(EQUAL, done)
    p.clamp_n(RAX, -LIM, LIM, R9)
    p.clamp_n(RCX, -LIM, LIM, R9)
    p.imin_n(RDX, 2 * LIM, R9)
    p.imin_n(R8, 2 * LIM, R9)
    p.st("X0", RAX)
    p.st("Y0", RCX)
    p.st("W", RDX)
    p.st("H", R8)
    a.op("add", RAX, RDX)
    p.st("X1", RAX)
    a.op("add", RCX, R8)
    p.st("Y1", RCX)
    a.set(R9, 0xFFFFFF)
    for name, offset, colour in STYLE_FIELDS:
        a.load(RAX, RBX, offset)
        if colour:
            a.op("and", RAX, R9)
        p.st(name, RAX)
    p.ld(RAX, "transp")
    p.opacity(RAX, RCX)
    a.op("test", RAX, RAX)
    a.jump_if(EQUAL, done)
    a.call("paint_eclip")
    p.ld(RAX, "shadow")
    a.op("test", RAX, RAX)
    no_shadow = p.label("no_shadow")
    a.jump_if(NOT_GREATER, no_shadow)
    p.imin_n(RAX, 1024, RCX)
    p.st("shadow", RAX)
    a.call("paint_shadow")
    a.label(no_shadow)
    # the part of the box inside the clip
    p.ld(RAX, "X0")
    p.ld(RCX, "ex0")
    p.imax(RAX, RCX)
    p.st("cxa", RAX)
    p.ld(RDX, "X1")
    p.ld(RCX, "ex1")
    p.imin(RDX, RCX)
    p.st("cxb", RDX)
    a.op("cmp", RAX, RDX)
    a.jump_if(NOT_LESS, done)
    a.op("sub", RDX, RAX)
    p.st("n", RDX)
    p.ld(RAX, "Y0")
    p.ld(RCX, "ey0")
    p.imax(RAX, RCX)
    p.st("rya", RAX)
    p.ld(RDX, "Y1")
    p.ld(RCX, "ey1")
    p.imin(RDX, RCX)
    p.st("ryb", RDX)
    a.op("cmp", RAX, RDX)
    a.jump_if(NOT_LESS, done)
    # settle the style
    p.ld(RAX, "tsize")
    a.set(RCX, 8)
    a.op("test", RAX, RAX)
    a.move_if(NOT_GREATER, RAX, RCX)
    p.clamp_n(RAX, 2, 4096, RCX)
    p.st("tsize", RAX)
    a.mov(RCX, RAX)
    a.shift_right(RCX, 3)
    p.imax_n(RCX, 1, RDX)
    p.st("lw", RCX)                      # line width of the marks (and the grain size)
    a.mov(RCX, RAX)
    a.multiply(RCX, RAX)
    a.shift_right(RCX, 2)
    p.st("dthr", RCX)                    # dots: (s * s) / 4
    a.set(RDX, 0)
    a.set(RCX, 3)
    a.divide(RCX)
    p.imax_n(RAX, 1, RCX)
    p.st("s3", RAX)                      # stripes: s / 3
    p.ld(RAX, "tex")
    a.set(RCX, 0)
    a.op_n("cmp", RAX, 1)
    a.move_if(LESS, RAX, RCX)
    a.op_n("cmp", RAX, 8)
    a.move_if(GREATER, RAX, RCX)
    p.st("tex", RAX)
    p.ld(RAX, "bw")
    p.clamp_n(RAX, 0, 2 * LIM, RCX)
    p.st("bw", RAX)
    p.float_of(X0, RAX)
    p.stx("bwf", X0)
    p.ld(RAX, "fill")
    a.set(RCX, 0)
    a.set(RDX, 255)
    no_fill = p.label("no_fill")
    a.op_n("cmp", RAX, 1)
    a.jump_if(LESS, no_fill)
    a.op_n("cmp", RAX, 3)
    a.jump_if(GREATER, no_fill)
    a.mov(RCX, RDX)
    a.label(no_fill)
    p.st("af", RCX)
    p.ld(RAX, "rad")
    a.set(RCX, 0)
    p.imax(RAX, RCX)
    p.ld(RCX, "W")
    a.shift_right(RCX, 1)
    p.imin(RAX, RCX)
    p.ld(RCX, "H")
    a.shift_right(RCX, 1)
    p.imin(RAX, RCX)
    p.st("rad", RAX)
    p.ld(RAX, "dir")
    a.set(RCX, 0)
    a.op_n("cmp", RAX, 0)
    a.move_if(LESS, RAX, RCX)
    a.op_n("cmp", RAX, 5)
    a.move_if(GREATER, RAX, RCX)
    p.st("dir", RAX)
    # the middle and size, as decimals
    for centre, start, size, inv in (("gcx", "X0", "W", "irx"), ("gcy", "Y0", "H", "iry")):
        p.ld(RAX, start)
        a.op("add", RAX, RAX)
        p.ld(RCX, size)
        a.op("add", RAX, RCX)
        p.float_of(X0, RAX)
        p.mulk(X0, 0.5)
        p.stx(centre, X0)
        p.k(X0, 2.0)
        p.float_of(X1, RCX)
        a.decimal_maths("div", X0, X1)
        p.stx(inv, X0)
    gradient_setup(p)
    # ellipse: its half sizes, and the inner ellipse whose pixels are surely all fill
    p.var_float(X0, "W")
    p.mulk(X0, 0.5)
    p.var_float(X1, "H")
    p.mulk(X1, 0.5)
    for half, inv, inv2, xmm in (("ea", "ia", "ia2", X0), ("eb", "ib", "ib2", X1)):
        p.stx(half, xmm)
        p.k(X2, 1.0)
        a.decimal_maths("div", X2, xmm)
        p.stx(inv, X2)
        a.decimal_maths("mul", X2, X2)
        p.stx(inv2, X2)
    a.copy_decimal(X2, X0)
    a.decimal_max(X2, X1)                # big
    a.copy_decimal(X3, X0)
    a.decimal_min(X3, X1)                # small
    p.k(X4, 0.0)
    a.decimal_maths("sub", X4, X3)
    p.stx("ecentre", X4)
    p.ldx(X4, "bwf")
    p.addk(X4, 1.0)
    a.decimal_maths("mul", X4, X2)
    a.decimal_maths("div", X4, X3)
    a.decimal_maths("sub", X0, X4)
    p.stx("ai", X0)
    a.decimal_maths("sub", X1, X4)
    p.stx("bi", X1)
    # row after row
    p.ld(RAX, "rya")
    row = p.label("row")
    a.label(row)
    p.st("py", RAX)
    p.ld(RCX, "Y0")
    a.op("sub", RAX, RCX)
    p.st("v", RAX)
    a.call("paint_row_fill")
    p.ld(RAX, "tex")
    a.op("test", RAX, RAX)
    no_tex = p.label("no_tex")
    a.jump_if(EQUAL, no_tex)
    a.call("paint_row_texture")
    a.label(no_tex)
    p.ld(RAX, "shape")
    a.op("test", RAX, RAX)
    box = p.label("row_box")
    shaped = p.label("shaped")
    a.jump_if(EQUAL, box)
    a.call("paint_row_ellipse")
    a.jump(shaped)
    a.label(box)
    a.call("paint_row_box")
    a.label(shaped)
    a.call("paint_row_blend")
    p.ld(RAX, "py")
    a.op_n("add", RAX, 1)
    p.ld(RCX, "ryb")
    a.op("cmp", RAX, RCX)
    a.jump_if(LESS, row)
    a.label(done)
    a.ret()


def gradient_setup(p):
    """Tables made once per box: columns (right / left), diagonals, or the 256 radial colours."""
    a = p.a
    done = p.label("grad_done")
    p.ld(RAX, "fill")
    a.op_n("cmp", RAX, 3)
    radial = p.label("radial_setup")
    a.jump_if(EQUAL, radial)
    a.op_n("cmp", RAX, 2)
    a.jump_if(NOT_EQUAL, done)
    p.ld(RAX, "dir")
    a.op_n("cmp", RAX, 2)
    a.jump_if(LESS, done)               # down / up: a colour per row, made in the row
    a.op_n("cmp", RAX, 4)
    diagonal = p.label("diag_setup")
    a.jump_if(NOT_LESS, diagonal)
    # columns: table[i] for x = cxa + i
    a.set(R12, 0)
    a.address(R13, "paint_gtab")
    loop = p.label("col_loop")
    a.label(loop)
    p.ld(RDX, "cxa")
    a.op("add", RDX, R12)
    p.ld(RCX, "X0")
    a.op("sub", RDX, RCX)               # u
    p.ld(R8, "W")
    a.op_n("sub", R8, 1)
    p.ld(RAX, "dir")
    a.op_n("cmp", RAX, 2)
    keep = p.label("col_keep")
    a.jump_if(EQUAL, keep)
    a.mov(RAX, R8)
    a.op("sub", RAX, RDX)
    a.mov(RDX, RAX)                     # w - 1 - u
    a.label(keep)
    p.ld(RAX, "c1")
    p.ld(RCX, "c2")
    a.call("paint_lerp")
    a.store32(R13, 0, RAX)
    a.op_n("add", R13, 4)
    a.op_n("add", R12, 1)
    p.ld(RAX, "n")
    a.op("cmp", R12, RAX)
    a.jump_if(LESS, loop)
    a.jump(done)
    # diagonals: table[j] for k = kmin + j, where k = u + (v or h - 1 - v)
    a.label(diagonal)
    p.ld(RAX, "dir")
    p.ld(RCX, "rya")
    p.ld(RDX, "Y0")
    a.op("sub", RCX, RDX)               # first v
    a.op_n("cmp", RAX, 4)
    first = p.label("diag_min")
    a.jump_if(EQUAL, first)
    p.ld(RCX, "ryb")
    a.op_n("sub", RCX, 1)
    a.op("sub", RCX, RDX)               # last v
    p.ld(RAX, "H")
    a.op_n("sub", RAX, 1)
    a.op("sub", RAX, RCX)
    a.mov(RCX, RAX)                     # h - 1 - last v
    a.label(first)
    p.ld(RAX, "cxa")
    a.op("add", RCX, RAX)
    p.ld(RAX, "X0")
    a.op("sub", RCX, RAX)
    p.st("kmin", RCX)
    p.ld(RBP, "n")
    p.ld(RAX, "ryb")
    a.op("add", RBP, RAX)
    p.ld(RAX, "rya")
    a.op("sub", RBP, RAX)
    a.op_n("sub", RBP, 1)               # how many diagonals
    a.set(R12, 0)
    a.address(R13, "paint_gtab")
    loop = p.label("diag_loop")
    a.label(loop)
    p.ld(RDX, "kmin")
    a.op("add", RDX, R12)
    p.ld(R8, "W")
    p.ld(RAX, "H")
    a.op("add", R8, RAX)
    a.op_n("sub", R8, 2)
    p.ld(RAX, "c1")
    p.ld(RCX, "c2")
    a.call("paint_lerp")
    a.store32(R13, 0, RAX)
    a.op_n("add", R13, 4)
    a.op_n("add", R12, 1)
    a.op("cmp", R12, RBP)
    a.jump_if(LESS, loop)
    a.jump(done)
    # radial: 256 colours from the middle to the edge
    a.label(radial)
    a.set(R12, 0)
    a.address(R13, "paint_rtab")
    loop = p.label("rad_loop")
    a.label(loop)
    a.mov(RDX, R12)
    a.set(R8, 255)
    p.ld(RAX, "c1")
    p.ld(RCX, "c2")
    a.call("paint_lerp")
    a.store32(R13, 0, RAX)
    a.op_n("add", R13, 4)
    a.op_n("add", R12, 1)
    a.op_n("cmp", R12, 256)
    a.jump_if(LESS, loop)
    a.label(done)


def row_fill(p):
    """paint_row_fill: the fill colours of row py into paint_rowc, alpha into paint_rowa."""
