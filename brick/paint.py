def blend_constant(p, ptr):
    """The colour 'pcol' (spread: 'psp') at alpha rdx (1..255) over the pixel at [ptr]. Changes rax, rcx, r8, r9."""
    a = p.a
    full = p.label("bc_full")
    done = p.label("bc_done")
    a.op_n("cmp", RDX, 255)
    a.jump_if(EQUAL, full)
    a.load32(R8, ptr, 0)
    p.ld(RAX, "psp")
    p.mix(spread_src=True)
    a.store32(ptr, 0, RAX)
    a.jump(done)
    a.label(full)
    p.ld(RAX, "pcol")
    a.store32(ptr, 0, RAX)
    a.label(done)


def set_colour(p, reg):
    """'pcol' = the colour in reg (cut to 0xRRGGBB), 'psp' = it spread."""
    a = p.a
    a.set(RCX, 0xFFFFFF)
    a.op("and", reg, RCX)
    p.st("pcol", reg)
    p.spread(reg, RCX, R9)
    p.st("psp", reg)


def line_routine(p):
    a = p.a
    a.label("paint_line")
    p.enter()
    done = p.label("line_done")
    a.mov(RSI, RAX)
    a.load(RAX, RSI, 48)
    p.opacity(RAX, RCX)
    a.op("test", RAX, RAX)
    a.jump_if(EQUAL, done)
    for i, name in enumerate(("lx1", "ly1", "lx2", "ly2")):
        a.load(RAX, RSI, 8 * i)
        p.clamp_n(RAX, -LIM, LIM, RCX)
        p.st(name, RAX)
    a.load(RAX, RSI, 32)
    set_colour(p, RAX)
    a.load(RAX, RSI, 40)
    a.set(RCX, 1)
    a.op("test", RAX, RAX)
    a.move_if(NOT_GREATER, RAX, RCX)
    p.imin_n(RAX, 4096, RCX)
    p.float_of(X0, RAX)
    p.mulk(X0, 0.5)
    p.addk(X0, 0.5)
    p.stx("lrr", X0)
    a.shift_right(RAX, 1)
    a.op_n("add", RAX, 2)
    p.st("lm", RAX)                     # how far past the ends anything can show
    p.ld(RAX, "lx2")
    p.ld(RCX, "lx1")
    a.op("sub", RAX, RCX)
    p.float_of(X0, RAX)
    p.stx("lvx", X0)
    p.ld(RAX, "ly2")
    p.ld(RCX, "ly1")
    a.op("sub", RAX, RCX)
    p.float_of(X1, RAX)
    p.stx("lvy", X1)
    a.decimal_maths("mul", X0, X0)
    a.copy_decimal(X2, X1)
    a.decimal_maths("mul", X2, X1)
    a.decimal_maths("add", X0, X2)      # l2
    p.k(X3, 0.0)
    a.copy_decimal(X4, X3)
    a.compare_decimals(X0, X3)
    zero = p.label("line_l2_zero")
    a.jump_if(NOT_ABOVE, zero)
    p.k(X4, 1.0)
    a.decimal_maths("div", X4, X0)
    a.label(zero)
    p.stx("linv", X4)
    # band: within hw of the line's x on each row (only when the line is not flat)
    a.set(RCX, 0)
    p.st("lband", RCX)
    p.ld(RAX, "ly2")
    p.ld(RCX, "ly1")
    a.op("cmp", RAX, RCX)
    flat = p.label("line_flat")
    a.jump_if(EQUAL, flat)
    a.set(RCX, 1)
    p.st("lband", RCX)
    a.square_root(X0, X0)
    p.var_float(X2, "lm")
    a.decimal_maths("mul", X0, X2)
    p.k(X2, "abs")
    a.copy_decimal(X3, X1)
    a.decimal_and(X3, X2)
    a.decimal_maths("div", X0, X3)
    p.stx("lhw", X0)
    p.ldx(X0, "lvx")
    a.decimal_maths("div", X0, X1)
    p.stx("lslope", X0)
    a.label(flat)
    a.call("paint_eclip")
    # rows and columns that can show anything
    p.ld(RAX, "lx1")
    p.ld(RCX, "lx2")
    a.mov(RDX, RAX)
    p.imin(RAX, RCX)
    p.imax(RDX, RCX)
    p.ld(RCX, "lm")
    a.op("sub", RAX, RCX)
    a.op("add", RDX, RCX)
    a.op_n("add", RDX, 1)
    p.st("lminx", RAX)
    p.st("lmaxx", RDX)
    p.ld(RAX, "ly1")
    p.ld(R8, "ly2")
    a.mov(RDX, RAX)
    p.imin(RAX, R8)
    p.imax(RDX, R8)
    a.op("sub", RAX, RCX)
    a.op("add", RDX, RCX)
    a.op_n("add", RDX, 1)
    p.ld(RCX, "ey0")
    p.imax(RAX, RCX)
    p.ld(RCX, "ey1")
    p.imin(RDX, RCX)
    p.st("lyb", RDX)
    a.op("cmp", RAX, RDX)
    a.jump_if(NOT_LESS, done)
    a.mov(R13, RAX)
    row = p.label("line_row")
    next_row = p.label("line_next_row")
    a.label(row)
    p.ld(R12, "lminx")
    p.ld(RAX, "ex0")
    p.imax(R12, RAX)
    p.ld(RBP, "lmaxx")
    p.ld(RAX, "ex1")
    p.imin(RBP, RAX)
    p.ld(RAX, "lband")
    a.op("test", RAX, RAX)
    no_band = p.label("line_no_band")
    a.jump_if(EQUAL, no_band)
    a.mov(RAX, R13)
    p.ld(RCX, "ly1")
    a.op("sub", RAX, RCX)
    p.float_of(X0, RAX)
    p.opv("mul", X0, "lslope")
    p.var_float(X1, "lx1")
    a.decimal_maths("add", X0, X1)      # the line's x on this row
    a.copy_decimal(X1, X0)
    p.opv("sub", X1, "lhw")
    a.round_decimal(X1, X1, 1)
    a.decimal_to_whole(RAX, X1)
    p.imax(R12, RAX)
    p.opv("add", X0, "lhw")
    a.round_decimal(X0, X0, 2)
    a.decimal_to_whole(RAX, X0)
    a.op_n("add", RAX, 1)
    p.imin(RBP, RAX)
    a.label(no_band)
    a.op("cmp", R12, RBP)
    a.jump_if(NOT_LESS, next_row)
    a.mov(RAX, R13)
    p.ld(RCX, "ly1")
    a.op("sub", RAX, RCX)
    p.float_of(X6, RAX)                 # fy
    a.copy_decimal(X7, X6)
    p.opv("mul", X7, "lvy")             # fy * vy
    p.ldx(X8, "lvx")
    p.ldx(X9, "lvy")
    p.ldx(X10, "linv")
    p.ldx(X11, "lrr")
    p.k(X12, 0.0)
    p.k(X13, 1.0)
    p.k(X14, 255.0)
    p.row_address(RBX, R13, R12, RAX)
    loop = p.label("line_loop")
    after = p.label("line_next")
    a.label(loop)
    a.mov(RAX, R12)
    p.ld(RCX, "lx1")
    a.op("sub", RAX, RCX)
    p.float_of(X0, RAX)                 # fx
    a.copy_decimal(X1, X0)
    a.decimal_maths("mul", X1, X8)
    a.decimal_maths("add", X1, X7)
    a.decimal_maths("mul", X1, X10)
    a.decimal_max(X1, X12)
    a.decimal_min(X1, X13)              # tt
    a.copy_decimal(X2, X1)
    a.decimal_maths("mul", X2, X8)
    a.decimal_maths("sub", X0, X2)      # qx
    a.decimal_maths("mul", X1, X9)
    a.copy_decimal(X2, X6)
    a.decimal_maths("sub", X2, X1)      # qy
    a.decimal_maths("mul", X0, X0)
    a.decimal_maths("mul", X2, X2)
    a.decimal_maths("add", X0, X2)
    a.square_root(X0, X0)
    a.copy_decimal(X1, X11)
    a.decimal_maths("sub", X1, X0)
    a.decimal_maths("mul", X1, X14)
    p.addk(X1, 0.5)
    p.to_alpha(RDX, X1)
    a.op("test", RDX, RDX)
    a.jump_if(EQUAL, after)
    p.ld(RAX, "op")
    a.multiply(RDX, RAX)
    p.div255(RDX, RCX)
    a.op("test", RDX, RDX)
    a.jump_if(EQUAL, after)
    blend_constant(p, RBX)
    a.label(after)
    a.op_n("add", RBX, 4)
    a.op_n("add", R12, 1)
    a.op("cmp", R12, RBP)
    a.jump_if(LESS, loop)
    a.label(next_row)
    a.op_n("add", R13, 1)
    p.ld(RAX, "lyb")
    a.op("cmp", R13, RAX)
    a.jump_if(LESS, row)
    a.label(done)
    a.ret()


def floor_divide(p):
    """rax = floor(rax / rcx), rcx > 0. Changes rdx."""
    a = p.a
    a.sign_extend()
    a.divide(RCX, signed=True)
    a.op("test", RDX, RDX)
    exact = p.label("fd_ok")
    a.jump_if(0x9, exact)               # NOT_NEGATIVE
    a.op_n("sub", RAX, 1)
    a.label(exact)


def triangle_routine(p):
    a = p.a
    a.label("paint_triangle")
    p.enter()
    done = p.label("tri_done")
    a.mov(RSI, RAX)
    a.load(RAX, RSI, 56)
    p.opacity(RAX, RCX)
    a.op("test", RAX, RAX)
    a.jump_if(EQUAL, done)
    a.load(RAX, RSI, 48)
    set_colour(p, RAX)
    regs = [R8, R9, R10, R11, R12, R13]
    for i, reg in enumerate(regs):
        a.load(reg, RSI, 8 * i)
        p.clamp_n(reg, -LIM, LIM, RAX)
    x1, y1, x2, y2, x3, y3 = regs
    # area: (x2 - x1)(y3 - y1) - (y2 - y1)(x3 - x1); turn it round if negative
    a.mov(RAX, x2)
    a.op("sub", RAX, x1)
    a.mov(RCX, y3)
    a.op("sub", RCX, y1)
    a.multiply(RAX, RCX)
    a.mov(RDX, y2)
    a.op("sub", RDX, y1)
    a.mov(RCX, x3)
    a.op("sub", RCX, x1)
    a.multiply(RDX, RCX)
    a.op("sub", RAX, RDX)
    a.jump_if(EQUAL, done)
    keep = p.label("tri_keep")
    a.jump_if(GREATER, keep)
    for r1, r2 in ((x2, x3), (y2, y3)):
        a.mov(RAX, r1)
        a.mov(r1, r2)
        a.mov(r2, RAX)
    a.label(keep)
    for i, reg in enumerate(regs):
        p.st(f"tv{i}", reg)
    # each edge: a = -4 (by - ay), c = k1 py + k0
    for e, (i, j) in enumerate(((0, 1), (1, 2), (2, 0))):
        p.ld(R8, f"tv{2 * i}")          # ax
        p.ld(R9, f"tv{2 * i + 1}")      # ay
        p.ld(R10, f"tv{2 * j}")         # bx
        p.ld(R11, f"tv{2 * j + 1}")     # by
        a.mov(RAX, R11)
        a.op("sub", RAX, R9)            # by - ay
        a.mov(RCX, R10)
        a.op("sub", RCX, R8)            # bx - ax
        a.multiply_n(RDX, RAX, -4)
        p.st(f"ta{e}", RDX)
        a.multiply_n(RDX, RCX, 4)
        p.st(f"tk{e}", RDX)
        a.set(RDX, 1)
        a.op("sub", RDX, R9)
        a.op("sub", RDX, R9)            # 1 - 2ay
        a.multiply(RDX, RCX)
        a.op("add", RDX, RDX)           # 2 (bx - ax)(1 - 2ay)
        a.set(RBX, 1)
        a.op("sub", RBX, R8)
        a.op("sub", RBX, R8)            # 1 - 2ax
        a.multiply(RBX, RAX)
        a.op("add", RBX, RBX)
        a.op("sub", RDX, RBX)
        # the top-left rule: edges going up, or flat edges going right, keep pixels exactly on them
        a.set(RBX, 1)
        a.set(RDI, 0)
        a.op("test", RAX, RAX)
        a.move_if(LESS, RBX, RDI)       # by < ay
        flat_test = p.label("tri_tl")
        a.jump_if(NOT_EQUAL, flat_test)
        a.op("test", RCX, RCX)
        a.move_if(GREATER, RBX, RDI)    # flat and bx > ax
        a.label(flat_test)
        a.op("sub", RDX, RBX)
        p.st(f"t0{e}", RDX)
    a.call("paint_eclip")
    p.ld(RAX, "tv1")
    a.mov(RDX, RAX)
    for name in ("tv3", "tv5"):
        p.ld(RCX, name)
        p.imin(RAX, RCX)
        p.imax(RDX, RCX)
    p.ld(RCX, "ey0")
    p.imax(RAX, RCX)
    p.ld(RCX, "ey1")
    p.imin(RDX, RCX)
    p.st("tyb", RDX)
    a.op("cmp", RAX, RDX)
    a.jump_if(NOT_LESS, done)
    a.mov(R13, RAX)
    row = p.label("tri_row")
    next_row = p.label("tri_next_row")
    a.label(row)
    p.ld(R12, "ex0")
    p.ld(RBP, "ex1")
    for e in range(3):
        p.ld(RAX, f"tk{e}")
        a.multiply(RAX, R13)
        p.ld(RCX, f"t0{e}")
        a.op("add", RAX, RCX)           # c
        p.ld(RCX, f"ta{e}")
        a.op("test", RCX, RCX)
        up = p.label("tri_pos")
        down = p.label("tri_neg")
        after = p.label("tri_edge_done")
        a.jump_if(GREATER, up)
        a.jump_if(LESS, down)
        a.op("test", RAX, RAX)
        a.jump_if(NOT_NEGATIVE, after)
        a.jump(next_row)
        a.label(up)                     # x >= ceil(-c / a) = -floor(c / a)
        floor_divide(p)
        a.negate(RAX)
        p.imax(R12, RAX)
        a.jump(after)
        a.label(down)                   # x <= floor(c / -a)
        a.negate(RCX)
        floor_divide(p)
        a.op_n("add", RAX, 1)
        p.imin(RBP, RAX)
        a.label(after)
    a.op("cmp", R12, RBP)
    a.jump_if(NOT_LESS, next_row)
    p.row_address(RDI, R13, R12, RAX)
    a.mov(RCX, RBP)
    a.op("sub", RCX, R12)
    p.ld(RAX, "op")
    a.op_n("cmp", RAX, 255)
    blended = p.label("tri_blend")
    a.jump_if(NOT_EQUAL, blended)
    p.ld(RAX, "pcol")
    a.fill_dwords()
    a.jump(next_row)
    a.label(blended)
    a.mov(RBX, RCX)
    loop = p.label("tri_loop")
    a.label(loop)
    p.ld(RDX, "op")
    blend_constant(p, RDI)
    a.op_n("add", RDI, 4)
    a.op_n("sub", RBX, 1)
    a.jump_if(NOT_EQUAL, loop)
    a.label(next_row)
    a.op_n("add", R13, 1)
    p.ld(RAX, "tyb")
    a.op("cmp", R13, RAX)
    a.jump_if(LESS, row)
    a.label(done)
    a.ret()


# ---- text ----

def text_size(p, reg, tmp):
    """reg = the text size: 16 if not above 0, at most 1024."""
    a = p.a
    a.set(tmp, 16)
    a.op("test", reg, reg)
    a.move_if(NOT_GREATER, reg, tmp)
    p.imin_n(reg, 1024, tmp)


def scaled_width(p):
    """rax = (pen * s + b / 2) / b for 'tpen', 'ts', 'tb'."""
    a = p.a
    p.ld(RAX, "tpen")
    p.ld(RCX, "ts")
    a.multiply(RAX, RCX)
    p.ld(RCX, "tb")
    a.mov(RDX, RCX)
    a.shift_right(RDX, 1)
    a.op("add", RAX, RDX)
    a.set(RDX, 0)
    a.divide(RCX)


def glyph_walk(p, draw):
    """For each letter of the text 'tp'..'tend': (draw it), 'tpen' += its advance."""
    a = p.a
    loop = p.label("walk")
    done = p.label("walk_done")
    after = p.label("walk_next")
    a.set(RAX, 0)
    p.st("tpen", RAX)
    a.label(loop)
    p.ld(RSI, "tp")
    p.ld(RCX, "tend")
    a.op("cmp", RSI, RCX)
    a.jump_if(NOT_LESS, done)
    a.load_byte(RAX, RSI, 0)
    a.op_n("add", RSI, 1)
    p.st("tp", RSI)
    a.mov(RCX, RAX)
    a.op_n("sub", RCX, 0x80)
    a.op_n("cmp", RCX, 0x40)
    a.jump_if(0x2, loop)                # BELOW: 0x80..0xBF continue a letter
    a.mov(RCX, RAX)
    a.op_n("sub", RCX, 32)
    a.set(RDX, 95)
    a.op_n("cmp", RCX, 94)
    a.move_if(ABOVE, RCX, RDX)          # not 32..126: the box
    a.shift_left(RCX, 3)
    p.ld(RAX, "tf")
    a.op("add", RAX, RCX)
    a.op_n("add", RAX, 8)
    p.st("trec", RAX)
    if draw:
        p.ld(RCX, "op")
        a.op("test", RCX, RCX)
        a.jump_if(EQUAL, after)
        a.load_byte(RCX, RAX, 3)
        a.op("test", RCX, RCX)
        a.jump_if(EQUAL, after)
        a.load_byte(RCX, RAX, 4)
        a.op("test", RCX, RCX)
        a.jump_if(EQUAL, after)
        a.call("paint_glyph")
    a.label(after)
    p.ld(RAX, "trec")
    a.load_byte(RAX, RAX, 0)
    p.ld(RCX, "tpen")
    a.op("add", RCX, RAX)
    p.st("tpen", RCX)
    a.jump(loop)
    a.label(done)


def text_start(p, text_reg):
    """'tp', 'tend' from the text address; 'tf', 'tb' from the size 'ts'. Returns with EQUAL set if no text."""
    a = p.a
    a.mov(RSI, text_reg)
    a.set(RAX, 0)
    p.st("tp", RAX)
    p.st("tend", RAX)
    a.op("test", RSI, RSI)
    none = p.label("no_text")
    a.jump_if(EQUAL, none)
    a.load(RAX, RSI, 0)
    a.lea(RCX, RSI, 8)
    p.st("tp", RCX)
    a.op("add", RCX, RAX)
    p.st("tend", RCX)
    a.label(none)
    p.ld(RAX, "ts")
    a.call("paint_font_pick")
    p.st("tf", RAX)
    a.load16(RCX, RAX, 0)
    p.st("tb", RCX)


def text_routines(p):
    a = p.a
    a.label("paint_measure")
    p.enter()
    text_size(p, RCX, RDX)
    p.st("ts", RCX)
    text_start(p, RAX)
    glyph_walk(p, draw=False)
    scaled_width(p)
    a.push(RAX)
    p.ld(RAX, "tf")
    a.load16(RAX, RAX, 2)
    p.st("tpen", RAX)                   # the line height, scaled the same way
    scaled_width(p)
    a.mov(RCX, RAX)
    a.pop(RAX)
    a.ret()

    a.label("paint_text")
    p.enter()
    a.mov(RSI, RAX)
    a.load(RAX, RSI, 0)
    p.clamp_n(RAX, -LIM, LIM, RCX)
    p.st("tx", RAX)
    a.load(RAX, RSI, 8)
    p.clamp_n(RAX, -LIM, LIM, RCX)
    p.st("ty", RAX)
    a.load(RAX, RSI, 24)
    a.push(RSI)
    set_colour(p, RAX)
    a.pop(RSI)
    a.load(RAX, RSI, 32)
    text_size(p, RAX, RCX)
    p.st("ts", RAX)
    a.load(RAX, RSI, 40)
    p.opacity(RAX, RCX)
    a.load(RAX, RSI, 16)
    text_start(p, RAX)
    p.ld(RAX, "tb")
    a.shift_left(RAX, 16)
    p.ld(RCX, "ts")
    a.set(RDX, 0)
    a.divide(RCX)
    p.st("tstep", RAX)
    a.call("paint_eclip")
    glyph_walk(p, draw=True)
    scaled_width(p)
    a.ret()

    glyph_routine(p)


def glyph_routine(p):
    """paint_glyph: the letter whose record is at 'trec', at pen 'tpen' (baked units), scaled to 'ts'."""
    a = p.a
    a.label("paint_glyph")
    done = p.label("glyph_done")
    p.ld(RSI, "trec")
    for name, offset in (("gx", 1), ("gy", 2)):
        a.load_byte(RAX, RSI, offset)
        a.shift_left(RAX, 56)
        a.shift_right_signed(RAX, 56)
        p.st(name, RAX)
    a.load_byte(RAX, RSI, 3)
    p.st("gw", RAX)
    a.load_byte(RAX, RSI, 4)
    p.st("gh", RAX)
    a.load16(RAX, RSI, 6)
    p.ld(RCX, "tf")
    a.op("add", RAX, RCX)
    a.op_n("add", RAX, 776)
    p.st("gsrc", RAX)
    # the letter, unpacked to bytes (0..255) with a border of zeros all round
    p.ld(RAX, "gw")
    a.op_n("add", RAX, 2)
    p.st("gpw", RAX)
    p.ld(RCX, "gh")
    a.op_n("add", RCX, 2)
    a.multiply(RCX, RAX)
    a.address(RDI, "paint_glyph_buf")
    a.set(RAX, 0)
    a.fill_bytes()
    a.address(RDI, "paint_glyph_buf")
    p.ld(RAX, "gpw")
    a.op("add", RDI, RAX)
    a.op_n("add", RDI, 1)
    p.ld(RSI, "gsrc")
    a.set(R8, 0)                        # which half-byte
    p.ld(R9, "gh")
    p.ld(R11, "gw")
    rows = p.label("unpack_row")
    cols = p.label("unpack_col")
    a.label(rows)
    a.set(R10, 0)
    a.label(cols)
    a.mov(RAX, R8)
    a.shift_right(RAX, 1)
    a.op("add", RAX, RSI)
    a.load_byte(RAX, RAX, 0)
    a.mov(RCX, R8)
    a.op_n("and", RCX, 1)
    a.shift_left(RCX, 2)
    a.shift_right_cl(RAX)
    a.op_n("and", RAX, 15)
    a.multiply_n(RAX, RAX, 17)
    a.mov(RDX, RDI)
    a.op("add", RDX, R10)
    a.store_byte(RDX, 0, RAX)
    a.op_n("add", R8, 1)
    a.op_n("add", R10, 1)
    a.op("cmp", R10, R11)
    a.jump_if(LESS, cols)
    p.ld(RAX, "gpw")
    a.op("add", RDI, RAX)
    a.op_n("sub", R9, 1)
    a.jump_if(NOT_EQUAL, rows)
    # where it goes: ox = pen + gx, oy = gy (baked units); rows and columns that can show it
    p.ld(RAX, "tpen")
    p.ld(RCX, "gx")
    a.op("add", RAX, RCX)
    p.st("gox", RAX)

    def scaled(reg_value, extra, name):
        """name = trunc(reg_value * s / b) + extra (signed)."""
        a.mov(RAX, reg_value)
        p.ld(RCX, "ts")
        a.multiply(RAX, RCX)
        p.ld(RCX, "tb")
        a.sign_extend()
        a.divide(RCX, signed=True)
        a.op_n("add", RAX, extra)
        p.st(name, RAX)

    for origin, size, first, last, start, low, high in (("gox", "gw", "gxa", "gxb", "tx", "ex0", "ex1"),
                                                         ("gy", "gh", "gya", "gyb", "ty", "ey0", "ey1")):
        p.ld(RBX, origin)
        a.lea(RBX, RBX, -1)
        scaled(RBX, -2, first)
        p.ld(RBX, origin)
        p.ld(RCX, size)
        a.op("add", RBX, RCX)
        a.op_n("add", RBX, 1)
        scaled(RBX, 3, last)
        # cut to the clip: start + first >= low, start + last <= high
        p.ld(RAX, low)
        p.ld(RCX, start)
        a.op("sub", RAX, RCX)
        p.ld(RDX, first)
        p.imax(RDX, RAX)
        p.st(first, RDX)
        p.ld(RAX, high)
        a.op("sub", RAX, RCX)
        p.ld(RDX, last)
        p.imin(RDX, RAX)
        p.st(last, RDX)
    p.ld(RAX, "gxa")
    p.ld(RCX, "gxb")
    a.op("cmp", RAX, RCX)
    a.jump_if(NOT_LESS, done)
    p.ld(RAX, "gya")
    p.ld(RCX, "gyb")
    a.op("cmp", RAX, RCX)
    a.jump_if(NOT_LESS, done)
    p.ld(RAX, "gya")
    p.st("gyy", RAX)
    row = p.label("glyph_row")
    next_row = p.label("glyph_next_row")
    a.label(row)
    # lv = yy * step + step / 2 - 32768 - (oy << 16)
    p.ld(RAX, "gyy")
    p.ld(RCX, "tstep")
    a.multiply(RAX, RCX)
    a.shift_right(RCX, 1)
    a.op("add", RAX, RCX)
    a.op_n("sub", RAX, 32768)
    p.ld(RCX, "gy")
    a.shift_left(RCX, 16)
    a.op("sub", RAX, RCX)
    a.mov(R10, RAX)
    a.shift_right(R10, 8)
    a.op_n("and", R10, 255)             # fv
    a.shift_right_signed(RAX, 16)       # iv
    a.op_n("add", RAX, 1)
    p.ld(RCX, "gh")
    a.op("cmp", RAX, RCX)
    a.jump_if(ABOVE, next_row)          # iv + 1 must be 0..gh
    p.ld(RCX, "gpw")
    a.multiply(RAX, RCX)
    a.address(RSI, "paint_glyph_buf")
    a.op("add", RSI, RAX)               # row iv (in the padded letter)
    a.lea(RDI, RSI, 0)
    a.op("add", RDI, RCX)               # row iv + 1
    a.set(R11, 256)
    a.op("sub", R11, R10)
    # the row of the target
    p.ld(RAX, "ty")
    p.ld(RCX, "gyy")
    a.op("add", RAX, RCX)
    p.ld(R12, "gxa")
    p.ld(RCX, "tx")
    a.op("add", RCX, R12)
    p.row_address(RBX, RAX, RCX, RDX)
    p.ld(R13, "gxb")
    p.ld(RBP, "tstep")                  # lu = xx * step + step / 2 - 32768 - (ox << 16)
    a.multiply(RBP, R12)
    p.ld(RAX, "tstep")
    a.shift_right(RAX, 1)
    a.op("add", RBP, RAX)
    a.op_n("sub", RBP, 32768)
    p.ld(RAX, "gox")
    a.shift_left(RAX, 16)
    a.op("sub", RBP, RAX)
    p.ld(R14, "gw")                     # r14 is borrowed here (no decimals in this loop)
    loop = p.label("glyph_loop")
    after = p.label("glyph_next")
    have = p.label("glyph_have")
    a.label(loop)
    a.mov(RAX, RBP)
    a.shift_right_signed(RAX, 16)
    a.op_n("add", RAX, 1)               # iu + 1
    a.op("cmp", RAX, R14)
    a.jump_if(ABOVE, after)
    a.mov(RCX, RBP)
    a.shift_right(RCX, 8)
    a.op_n("and", RCX, 255)             # fu
    a.lea(R8, RSI, 0)
    a.op("add", R8, RAX)
    a.load_byte(RDX, R8, 0)             # c00
    a.mov(RAX, RCX)
    a.op("or", RAX, R10)
    a.jump_if(EQUAL, have)
    a.set(RAX, 256)
    a.op("sub", RAX, RCX)
    a.multiply(RDX, RAX)
    a.load_byte(R9, R8, 1)              # c10
    a.multiply(R9, RCX)
    a.op("add", RDX, R9)                # top
    a.mov(R9, R8)
    a.op("sub", R9, RSI)
    a.op("add", R9, RDI)
    a.load_byte(R8, R9, 0)              # c01
    a.multiply(R8, RAX)
    a.load_byte(R9, R9, 1)              # c11
    a.multiply(R9, RCX)
    a.op("add", R8, R9)                 # bottom
    a.multiply(RDX, R11)
    a.multiply(R8, R10)
    a.op("add", RDX, R8)
    a.op_n("add", RDX, 32768)
    a.shift_right(RDX, 16)
    a.label(have)
    a.op("test", RDX, RDX)
    a.jump_if(EQUAL, after)
    p.ld(RAX, "op")
    a.multiply(RDX, RAX)
    p.div255(RDX, RCX)
    a.op("test", RDX, RDX)
    a.jump_if(EQUAL, after)
    blend_constant(p, RBX)
    a.label(after)
    p.ld(RAX, "tstep")
    a.op("add", RBP, RAX)
    a.op_n("add", RBX, 4)
    a.op_n("add", R12, 1)
    a.op("cmp", R12, R13)
    a.jump_if(LESS, loop)
    a.address(R14, "paint_k")
    a.label(next_row)
    p.ld(RAX, "gyy")
    a.op_n("add", RAX, 1)
    p.st("gyy", RAX)
    p.ld(RCX, "gyb")
    a.op("cmp", RAX, RCX)
    a.jump_if(LESS, row)
    a.label(done)
    a.ret()


def add_all(a, text_sizes=None):
    """Add the painting routines (and the letters for text_sizes: a list of px sizes, or None = not known)."""
    a.space.setdefault("gui_target", 32)
    a.space.setdefault("gui_clip", 32)
    p = Writer(a)
    clip_routines(p)
    lerp_routine(p)
    shape_routine(p)
    row_fill(p)
    row_texture(p)
    edge_routine(p)
    row_box(p)
    row_ellipse(p)
    row_blend(p)
    shadow_routine(p)
    line_routine(p)
    triangle_routine(p)
    text_routines(p)
    font.add(a, text_sizes)
    a.space["paint_rowc"] = MAXW * 4
    a.space["paint_rowa"] = MAXW
    a.space["paint_rowm"] = MAXW
    a.space["paint_gtab"] = 2 * MAXW * 4
    a.space["paint_rtab"] = 256 * 4
    a.space["paint_glyph_buf"] = 16384
    a.space["paint_v"] = 8 * len(p.vars)
    a.data["paint_k"] = p.const_bytes()
